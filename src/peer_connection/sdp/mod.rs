/// The remote candidates an offer's `a=remote-candidates` lines name, as (address, port), of
/// the sections that carry candidates (RFC 8839 section 5.2). RFC 9429 section 5.8.2: they
/// "MUST be parsed ... but their values are ignored": one that does not parse refuses the
/// description; a full agent then only takes its default destination from them.
pub(crate) fn remote_candidates(desc: &SessionDescription) -> Result<Vec<(String, u16)>> {
    use sdp::attribute::{RemoteCandidates, TypedAttribute};
    let mut named = vec![];
    for m in &desc.media_descriptions {
        for a in m
            .attributes
            .iter()
            .filter(|a| a.key == ATTR_KEY_REMOTE_CANDIDATES)
        {
            let value = a.value.as_deref().unwrap_or_default();
            let parsed = RemoteCandidates::parse(value).map_err(|_| {
                Error::SdpInvalidValue(format!(
                    "a=remote-candidates:{value} (RFC 8839 section 5.2)"
                ))
            })?;
            if is_rejected_media(m) {
                continue;
            }
            named.extend(
                parsed
                    .candidates
                    .into_iter()
                    .filter(|c| c.component == 1)
                    .map(|c| (c.address, c.port)),
            );
        }
    }
    Ok(named)
}

/// The `ufrag` extension attribute of a candidate line (`candidate-attribute` without the
/// `candidate:` prefix), the ICE generation it names (RFC 8839 section 5.1, RFC 8838 section
/// 9).
pub(crate) fn candidate_line_ufrag(value: &str) -> Option<&str> {
    let fields: Vec<&str> = value.split_ascii_whitespace().collect();
    // foundation component transport priority address port "typ" type, then raddr/rport and
    // the extension pairs.
    let mut i = 8;
    while i + 1 < fields.len() {
        if fields[i] == "ufrag" {
            return Some(fields[i + 1]);
        }
        i += 2;
    }
    None
}
/// The `b=` lines that state a receive limit of `tias` bits per second: `b=TIAS:<tias>`
/// (RFC 3890) and `b=AS` (RFC 8866 section 5.8, kilobits per second) for peers that read only
/// that one, the smallest value from which RFC 9429 section 5.10 derives at least `tias`
/// ("TIAS = AS * 1000 * 0.95 - (50 * 40 * 8)").
pub(crate) fn receive_bandwidth_lines(tias: u64) -> [sdp::description::common::Bandwidth; 2] {
    use sdp::description::common::Bandwidth;
    let kbps = tias.saturating_add(50 * 40 * 8).div_ceil(950);
    [
        Bandwidth {
            experimental: false,
            bandwidth_type: "TIAS".to_owned(),
            bandwidth: tias,
        },
        Bandwidth {
            experimental: false,
            bandwidth_type: "AS".to_owned(),
            bandwidth: kbps,
        },
    ]
}

/// `a=ptime` (RFC 8866 section 6.4).
pub(crate) const ATTR_KEY_PTIME: &str = "ptime";
/// `a=maxptime` (RFC 8866 section 6.5).
pub(crate) const ATTR_KEY_MAXPTIME: &str = "maxptime";

/// The packet times a media section states (`a=ptime`, `a=maxptime`; RFC 8866 sections 6.4,
/// 6.5); a value that is not a whole number of milliseconds is not stated. RFC 8866 allows a
/// decimal `a=ptime`: it is rounded up.
pub(crate) fn media_packet_time(media: &MediaDescription) -> RTCPacketTime {
    let value = |key: &str| -> Option<u32> {
        let value = media.attribute(key)??.trim();
        match value.split_once('.') {
            None => value.parse().ok(),
            Some((whole, fraction)) => {
                let whole: u32 = if whole.is_empty() {
                    0
                } else {
                    whole.parse().ok()?
                };
                if !fraction.bytes().all(|b| b.is_ascii_digit()) {
                    return None;
                }
                Some(whole + u32::from(fraction.bytes().any(|b| b != b'0')))
            }
        }
    };
    RTCPacketTime {
        ptime: value(ATTR_KEY_PTIME),
        maxptime: value(ATTR_KEY_MAXPTIME),
    }
}

/// RFC 8859 section 4.7: `a=ptime` and `a=maxptime` are IDENTICAL-PER-PT, they "MUST have
/// identical values across all the media descriptions for a given RTP payload type when
/// repeated": two sections of one BUNDLE group that both state one and share a payload type
/// must state the same value. This endpoint writes one packet time for all its audio
/// sections, so its own descriptions hold it; a remote description that breaks it is refused.
pub(crate) fn check_bundled_packet_times(desc: &SessionDescription) -> Result<()> {
    for group in bundle_groups(desc) {
        let sections: Vec<&MediaDescription> = desc
            .media_descriptions
            .iter()
            .filter(|m| {
                !is_rejected_media(m)
                    && get_mid_value(m).is_some_and(|mid| group.contains(&mid.as_str()))
            })
            .collect();
        for (key, pick) in [
            (
                ATTR_KEY_PTIME,
                (|t: RTCPacketTime| t.ptime) as fn(RTCPacketTime) -> Option<u32>,
            ),
            (ATTR_KEY_MAXPTIME, |t: RTCPacketTime| t.maxptime),
        ] {
            let mut by_pt: HashMap<&str, u32> = HashMap::new();
            for media in &sections {
                let Some(value) = pick(media_packet_time(media)) else {
                    continue;
                };
                for pt in &media.media_name.formats {
                    match by_pt.get(pt.as_str()) {
                        Some(&other) if other != value => {
                            return Err(Error::SdpInvalidValue(format!(
                                "a={key} differs ({other} and {value}) for payload type {pt} \
                                 across bundled sections (RFC 8859 section 4.7)"
                            )));
                        }
                        Some(_) => {}
                        None => {
                            by_pt.insert(pt.as_str(), value);
                        }
                    }
                }
            }
        }
    }
    Ok(())
}

/// RFC 8859 section 4.3: an attribute of the IDENTICAL category is "repeated across all the
/// media descriptions under multiplexing" with the same value. RFC 9143 section 7.1.3 lets
/// an answer or a subsequent offer carry it in the tagged section only, from where it applies
/// to every bundled section (the note of section 4.3: such attributes "might not always be
/// explicitly encoded across all media descriptions"), so an absence is not a disagreement.
/// Two bundled sections that both carry one with different values are. A section that
/// carries one its tagged section lacks is not refused: RFC 9429 section 5.2.2 itself writes
/// `a=rtcp-mux-only` in a section a later offer adds and not in the tagged one, and a tagged
/// data section carries none of the RTP session's attributes. The category is rtci-sdp's
/// table (`sdp::attribute::mux`). The browser descriptions recorded by the interop harness
/// never disagree (Firefox carries `a=rtcp-rsize` and `a=extmap-allow-mixed` in the tagged
/// section only: absences).
pub(crate) fn check_bundled_identical_attributes(desc: &SessionDescription) -> Result<()> {
    use ::sdp::attribute::mux::{MuxCategory, category};
    let values = |media: &MediaDescription, key: &str| -> Option<Vec<String>> {
        let mut found: Vec<String> = media
            .attributes
            .iter()
            .filter(|a| a.key == key)
            .map(|a| {
                a.value
                    .as_deref()
                    .unwrap_or_default()
                    .split_whitespace()
                    .collect::<Vec<_>>()
                    .join(" ")
            })
            .collect();
        found.sort();
        (!found.is_empty()).then_some(found)
    };
    for media in &desc.media_descriptions {
        if is_rejected_media(media) {
            continue;
        }
        let Some(tagged) = tagged_section(desc, media) else {
            continue;
        };
        if std::ptr::eq(tagged, media) {
            continue;
        }
        let mut keys: Vec<&str> = media.attributes.iter().map(|a| a.key.as_str()).collect();
        keys.dedup();
        for key in keys {
            if category(key) != Some(MuxCategory::Identical) {
                continue;
            }
            let Some(own) = values(media, key) else {
                continue;
            };
            let mid = get_mid_value(media).map(String::as_str).unwrap_or_default();
            let tag = get_mid_value(tagged)
                .map(String::as_str)
                .unwrap_or_default();
            if let Some(theirs) = values(tagged, key)
                && theirs != own
            {
                return Err(Error::SdpInvalidValue(format!(
                    "a={key} differs between the bundled sections {mid} and {tag} (RFC 8859 \
                     section 4.3: IDENTICAL category)"
                )));
            }
        }
    }
    Ok(())
}

/// The Ta a description proposes (`a=ice-pacing`, RFC 8839 section 5.5: session level, a
/// value in milliseconds of 1 to 10 digits); `None` when it proposes none or the value is not
/// one (section 5.5: an agent that does not understand it uses the default).
pub(crate) fn remote_ice_pacing(desc: &SessionDescription) -> Option<std::time::Duration> {
    desc.attribute(ATTR_KEY_ICE_PACING)
        .map(|v| v.trim())
        .filter(|v| (1..=10).contains(&v.len()) && v.bytes().all(|b| b.is_ascii_digit()))
        .and_then(|v| v.parse::<u64>().ok())
        .map(std::time::Duration::from_millis)
}

/// The ICE options a description states (`a=ice-options`, RFC 8839 section 5.6), at session
/// level and in its media sections, each once, in order.
/// The options of an answer's `a=ice-options` line under `setting`, given the offer's
/// options (`remote_ice_options`): `trickle` first, then `ice2` (RFC 9429 section 5.3.1 for
/// [`AnswerIceOptions::AsOffered`]).
pub(crate) fn answer_ice_options(
    setting: AnswerIceOptions,
    offered: &[String],
) -> Vec<&'static str> {
    let offered = |option: &str| offered.iter().any(|o| o == option);
    let (trickle, ice2) = match setting {
        AnswerIceOptions::AsOffered => (offered("trickle"), offered("ice2")),
        AnswerIceOptions::TrickleAlways => (true, offered("ice2")),
        AnswerIceOptions::Always => (true, true),
    };
    [(trickle, "trickle"), (ice2, "ice2")]
        .into_iter()
        .filter_map(|(on, option)| on.then_some(option))
        .collect()
}

pub(crate) fn remote_ice_options(desc: &SessionDescription) -> Vec<String> {
    let mut out: Vec<String> = vec![];
    let values = desc
        .attributes
        .iter()
        .chain(
            desc.media_descriptions
                .iter()
                .flat_map(|m| m.attributes.iter()),
        )
        .filter(|a| a.key == ATTR_KEY_ICE_OPTIONS)
        .filter_map(|a| a.value.as_deref());
    for option in values.flat_map(str::split_whitespace) {
        if !out.iter().any(|o| o == option) {
            out.push(option.to_owned());
        }
    }
    out
}

