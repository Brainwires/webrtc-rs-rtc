/// Gives each audio and video section of a received description the session-level
/// `a=rtcp-xr` when it has none of its own (RFC 3611 section 5.1: the attribute "can be used
/// at the session or media level", and at media level it replaces the session's). Only the
/// parsed description changes.
pub(crate) fn inherit_session_rtcp_xr(desc: &mut SessionDescription) {
    let Some(session) = desc
        .attributes
        .iter()
        .find(|a| a.key == ATTR_KEY_RTCP_XR)
        .cloned()
    else {
        return;
    };
    for media in &mut desc.media_descriptions {
        if matches!(media.media_name.media.as_str(), "audio" | "video")
            && media.attribute(ATTR_KEY_RTCP_XR).is_none()
        {
            media.attributes.push(session.clone());
        }
    }
}

/// Gives each audio and video section of a received description the session-level
/// `a=extmap` lines it does not override (RFC 8285 section 5: the mappings may be "provided
/// per media stream ... or globally for all streams"; RFC 9429 section 5.8.1 stores them, and
/// section 5.3.1 has session-level attributes count as present in each m= section). A
/// section's own mapping for an id or a URI wins. Only the parsed description changes.
/// RFC 8285 section 5: "The definitions MUST be either all session level or all media level;
/// it is not permitted to mix the two styles." A received description that has `a=extmap`
/// lines at both levels is refused.
pub(crate) fn check_extmap_levels(desc: &SessionDescription) -> Result<()> {
    let at_session = desc.attributes.iter().any(|a| a.key == ATTR_KEY_EXT_MAP);
    if at_session
        && desc
            .media_descriptions
            .iter()
            .any(|m| m.attributes.iter().any(|a| a.key == ATTR_KEY_EXT_MAP))
    {
        return Err(Error::SdpInvalidValue(
            "a=extmap at both session and media level (RFC 8285 section 5)".to_owned(),
        ));
    }
    Ok(())
}

pub(crate) fn inherit_session_extmap(desc: &mut SessionDescription) {
    let session: Vec<(String, String, String)> = desc
        .attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_EXT_MAP)
        .filter_map(|a| a.value.clone())
        .filter_map(|value| {
            let mut tokens = value.split_whitespace();
            let id = tokens.next()?.split('/').next()?.to_owned();
            let uri = tokens.next()?.to_owned();
            Some((id, uri, value))
        })
        .collect();
    if session.is_empty() {
        return;
    }
    for media in &mut desc.media_descriptions {
        if !matches!(media.media_name.media.as_str(), "audio" | "video") {
            continue;
        }
        let own: Vec<(String, String)> = media
            .attributes
            .iter()
            .filter(|a| a.key == ATTR_KEY_EXT_MAP)
            .filter_map(|a| a.value.as_deref())
            .filter_map(|value| {
                let mut tokens = value.split_whitespace();
                let id = tokens.next()?.split('/').next()?.to_owned();
                Some((id, tokens.next()?.to_owned()))
            })
            .collect();
        for (id, uri, value) in &session {
            if !own
                .iter()
                .any(|(own_id, own_uri)| own_id == id || own_uri == uri)
            {
                media
                    .attributes
                    .push(sdp::description::common::Attribute::new(
                        ATTR_KEY_EXT_MAP.to_owned(),
                        Some(value.clone()),
                    ));
            }
        }
    }
}

/// Refuses a received description whose header extension mappings contradict each other
/// (RFC 8285 sections 5 and 7):
///
/// - an id in the valid range mapped to two different extensions in one m= section, or in
///   two m= sections of one BUNDLE group, which share one id space (section 5: "Each local
///   identifier potentially used in the stream is mapped to an extension"; section 7: "The
///   local identifiers MUST be unique in an RTP session"; "All the 'm=' lines in a BUNDLE
///   group are considered to be part of the same local identifier (ID) space");
/// - one extension (URI, form and attributes) mapped to two ids in a section (section 5:
///   "MUST NOT" appear more than once per stream) or, within a BUNDLE group, to different
///   ids (section 7: "it MUST use the same ID in all of these 'm=' lines").
///
/// The ids of the extended range (4096 to 4351) are left out: they may be repeated for
/// alternatives (section 7). Checked after the session-level mappings are inherited.
pub(crate) fn check_extmap_ids(desc: &SessionDescription) -> Result<()> {
    // (URI, encrypted form, attributes) under an id.
    type Mapping = (u16, (String, bool, Option<String>));
    // A section's mid and its mappings.
    type Section = (Option<String>, Vec<Mapping>);
    let sections: Vec<Section> = desc
        .media_descriptions
        .iter()
        .filter(|m| {
            !is_rejected_media(m) && matches!(m.media_name.media.as_str(), "audio" | "video")
        })
        .map(|m| {
            let lines = section_extmap_lines(m)?
                .into_iter()
                .map(|(uri, e)| (e.id, (uri, e.encrypted, e.attributes)))
                .collect();
            Ok((get_mid_value(m).cloned(), lines))
        })
        .collect::<Result<_>>()?;
    let groups = bundle_groups(desc);
    let group_of = |mid: &Option<String>| {
        mid.as_deref()
            .and_then(|mid| groups.iter().position(|g| g.contains(&mid)))
    };
    let mut scopes: HashMap<(Option<usize>, usize), Vec<Mapping>> = HashMap::new();
    for (n, (mid, lines)) in sections.iter().enumerate() {
        // A bundled section shares the group's id space; any other has its own.
        let scope = match group_of(mid) {
            Some(group) => (Some(group), 0),
            None => (None, n),
        };
        let seen = scopes.entry(scope).or_default();
        for (id, ext) in lines {
            for (seen_id, seen_ext) in seen.iter() {
                if seen_id == id && seen_ext != ext {
                    return Err(Error::SdpInvalidValue(format!(
                        "a=extmap id {id} maps both {} and {} (RFC 8285 sections 5 and 7)",
                        seen_ext.0, ext.0
                    )));
                }
                if seen_ext == ext && seen_id != id {
                    return Err(Error::SdpInvalidValue(format!(
                        "a=extmap maps {} to both id {seen_id} and id {id} (RFC 8285 sections 5 \
                         and 7)",
                        ext.0
                    )));
                }
            }
            seen.push((*id, ext.clone()));
        }
    }
    Ok(())
}

/// Gives the header extensions an offer numbered in the extended range (4096 to 4351) an id
/// this endpoint can use, or drops them (RFC 8285 section 7: "The answerer SHOULD select, at
/// most, one of the offered extensions with the same identifier and remap it to a free
/// identifier in the valid range for that extension to be usable"; likewise for more
/// extensions than the valid range holds).
///
/// Per section and extended id, the first alternative `supported` accepts for the section's
/// media kind is kept; it takes the id the description already maps that extension to, or
/// else the first id of [`local_extension_ids`] that no mapping of the description and none
/// in `taken` uses. The other alternatives, and extensions nothing accepts, are dropped. Only
/// the parsed description changes, so the media engine negotiates the remapped id and the
/// answer states it.
pub(crate) fn remap_answerer_assigned_extmaps(
    desc: &mut SessionDescription,
    supported: impl Fn(&str, &str) -> bool,
    taken: &[u16],
) {
    let parse = |value: &str| -> Option<(u32, String, String)> {
        let mut tokens = value.splitn(2, ' ');
        let entry = tokens.next()?;
        let rest = tokens.next()?.to_owned();
        let id = entry.split('/').next()?.parse::<u32>().ok()?;
        let uri = rest.split_whitespace().next()?;
        let effective = if uri == ENCRYPT_URI {
            rest.split_whitespace().nth(1).unwrap_or("").to_owned()
        } else {
            uri.to_owned()
        };
        Some((id, effective, rest))
    };
    let extended = |id: u32| (4096..=4351).contains(&id);
    if !desc.media_descriptions.iter().any(|m| {
        m.attributes
            .iter()
            .filter(|a| a.key == ATTR_KEY_EXT_MAP)
            .filter_map(|a| a.value.as_deref().and_then(parse))
            .any(|(id, _, _)| extended(id))
    }) {
        return;
    }
    // Ids the description maps in the valid range, and to what.
    let mut used: Vec<(u16, String)> = desc
        .media_descriptions
        .iter()
        .flat_map(|m| m.attributes.iter())
        .chain(desc.attributes.iter())
        .filter(|a| a.key == ATTR_KEY_EXT_MAP)
        .filter_map(|a| a.value.as_deref().and_then(parse))
        .filter(|(id, _, _)| (1..=255).contains(id))
        .map(|(id, _, rest)| (id as u16, rest))
        .collect();
    for media in &mut desc.media_descriptions {
        let kind = media.media_name.media.clone();
        let mut chosen: HashSet<u32> = HashSet::new();
        let mut attributes = Vec::with_capacity(media.attributes.len());
        for mut attribute in std::mem::take(&mut media.attributes) {
            let parsed = (attribute.key == ATTR_KEY_EXT_MAP)
                .then(|| attribute.value.as_deref().and_then(parse))
                .flatten();
            let Some((id, effective, rest)) = parsed.filter(|(id, _, _)| extended(*id)) else {
                attributes.push(attribute);
                continue;
            };
            if chosen.contains(&id) || !supported(&kind, &effective) {
                continue;
            }
            let new_id = used
                .iter()
                .find(|(_, r)| *r == rest)
                .map(|(i, _)| *i)
                .or_else(|| {
                    local_extension_ids()
                        .find(|i| !taken.contains(i) && !used.iter().any(|(u, _)| u == i))
                });
            let Some(new_id) = new_id else {
                continue;
            };
            chosen.insert(id);
            if !used.iter().any(|(u, r)| *u == new_id && *r == rest) {
                used.push((new_id, rest.clone()));
            }
            let direction = attribute
                .value
                .as_deref()
                .and_then(|v| v.split(' ').next())
                .and_then(|entry| entry.split_once('/'))
                .map(|(_, d)| format!("/{d}"))
                .unwrap_or_default();
            attribute.value = Some(format!("{new_id}{direction} {rest}"));
            attributes.push(attribute);
        }
        media.attributes = attributes;
    }
}

/// The direction an answer gives each extension of an offered section that restricts one
/// (RFC 8285 section 7), by URI: sendonly is answered recvonly, recvonly sendonly, inactive
/// inactive. An extension offered without a direction (or sendrecv) is not in the map.
pub(crate) fn answered_extension_directions(
    m: &MediaDescription,
) -> HashMap<String, sdp::direction::Direction> {
    use sdp::direction::Direction;
    let mut out = HashMap::new();
    for (uri, mapping) in rtp_extensions_from_media_description(m).unwrap_or_default() {
        let answered = match mapping.direction {
            Direction::SendOnly => Direction::RecvOnly,
            Direction::RecvOnly => Direction::SendOnly,
            Direction::Inactive => Direction::Inactive,
            _ => continue,
        };
        out.insert(uri, answered);
    }
    out
}

/// Drops the `a=bundle-only` attributes of a received description that do not mean
/// "this section has port zero because it is only reachable through its BUNDLE group":
///
/// - RFC 9143 section 6: "If an offerer or answerer receives a 'bundle-only' attribute in a
///   non-bundled 'm=' section, the offerer or answerer MUST discard the attribute." Without
///   it a port-zero section is what port zero says: rejected (RFC 3264 section 6).
/// - RFC 9143 sections 7.3.2 and 7.3.3 and RFC 9429 section 5.3.1: no m= section of an
///   answer has the attribute, so one in an answer is discarded too. [`is_rejected_media`]
///   relies on this for every answer it reads: a zero port in an answer is a rejection.
///
/// Only the parsed description changes: the SDP text stays as given.
pub(crate) fn discard_stray_bundle_only(desc: &mut SessionDescription, answers: bool) {
    let bundled: HashSet<String> = bundle_groups(desc)
        .into_iter()
        .flatten()
        .map(str::to_owned)
        .collect();
    for media in &mut desc.media_descriptions {
        let in_group = get_mid_value(media).is_some_and(|mid| bundled.contains(mid.as_str()));
        if answers || !in_group {
            media.attributes.retain(|a| a.key != ATTR_KEY_BUNDLE_ONLY);
        }
    }
}

/// RFC 9429 section 5.8: "If any line is not well formed or cannot be parsed as described,
/// the parser MUST stop with an error and reject the session description, even if the value
/// is to be discarded." `unmarshal` checks every line type; this checks the value of every
/// attribute, at session and media level, by the grammar of its name
/// ([`sdp::attribute::check_attribute`]: `a=rtcp` by RFC 3605 section 2.1, which section
/// 5.8.2 asks to be parsed although its value is ignored, and every other attribute rtci-sdp
/// has a type for; an unknown attribute is ignored, RFC 8866 section 5.13).
///
/// The exceptions are the lines another specification has the receiver ignore when they are
/// malformed, which the reader of each then skips:
/// - `a=msid`: RFC 8830 section 2, "If the 'msid' attribute does not conform to the ABNF
///   given here, it SHOULD be ignored" (`media_msid`), and the `msid` source attribute
///   (`a=ssrc:<id> msid:...`, appendix A) likewise;
/// - `a=rid`: RFC 8851 section 6.2.2 step 1, "In the case of a syntax error, the 'a=rid'
///   line is discarded" (`section_rids`).
///
/// Unless `strict`, white space at the end of a value is not held against it
/// (`SettingEngineBuilder::with_strict_sdp_attribute_grammar`: webrtc-rs 0.17.x ends an
/// `a=rtcp-fb` without parameters with a space, against RFC 4585 section 4.2's
/// `rtcp-fb-param`; Pion did before v4.1.5).
///
/// `a=simulcast` is checked with `rid_ids` (`SettingEngine::rid_id_grammar`), the rid-id
/// grammar `section_rids` reads it with.
pub(crate) fn check_attribute_lines(
    desc: &SessionDescription,
    strict: bool,
    rid_ids: RidIdGrammar,
) -> Result<()> {
    // RFC 8866 section 6.7: "At most one occurrence of "a=recvonly", "a=sendrecv",
    // "a=sendonly", or "a=inactive" MAY appear at session level, and at most one MAY appear
    // in each media description": a level with two is ambiguous, and refused.
    desc.direction()?;
    for media in &desc.media_descriptions {
        media.direction()?;
    }
    let lines = desc.attributes.iter().chain(
        desc.media_descriptions
            .iter()
            .flat_map(|media| media.attributes.iter()),
    );
    for a in lines.filter(|a| !MALFORMED_IGNORED.contains(&a.key.as_str())) {
        let trimmed;
        let a = match a.value.as_deref() {
            Some(value) if !strict && value.len() != value.trim_end().len() => {
                trimmed = sdp::description::common::Attribute::new(
                    a.key.clone(),
                    Some(value.trim_end().to_owned()),
                );
                &trimmed
            }
            _ => a,
        };
        match a.value.as_deref().and_then(|v| v.split_once(' ')) {
            // `msid` is also a source attribute (RFC 8830 appendix A), ignored when malformed
            // as the media-level one is: the line's SSRC and attribute name are checked.
            Some((id, source)) if a.key == ATTR_KEY_SSRC && source.starts_with("msid:") => {
                sdp::attribute::check_attribute(&sdp::description::common::Attribute::new(
                    ATTR_KEY_SSRC.to_owned(),
                    Some(format!("{id} msid-ignored")),
                ))?;
            }
            _ if a.key == SDP_ATTRIBUTE_SIMULCAST => {
                sdp::attribute::Simulcast::parse_with(
                    a.value.as_deref().unwrap_or_default(),
                    rid_ids,
                )?;
            }
            _ => sdp::attribute::check_attribute(a)?,
        }
    }
    Ok(())
}

/// The attributes whose malformed lines are ignored rather than refused (see
/// [`check_attribute_lines`]).
const MALFORMED_IGNORED: [&str; 2] = ["msid", "rid"];

/// RFC 5888 section 6: "'a=group' lines that contain identification-tags that do not
/// correspond to any 'm' line within the session description MUST be ignored. The
/// application acts as if the 'a=group' line did not exist." Such lines (of any semantics)
/// are taken out of the parsed description; the SDP text stays as given. In an answer a
/// BUNDLE group is kept: RFC 9143 section 7.4 makes one that names a section the offer did
/// not bundle an error, which the answer check reports.
pub(crate) fn discard_groups_with_unknown_tags(desc: &mut SessionDescription, answers: bool) {
    let mids: HashSet<String> = desc
        .media_descriptions
        .iter()
        .filter_map(|media| get_mid_value(media).cloned())
        .collect();
    desc.attributes.retain(|a| {
        a.key != ATTR_KEY_GROUP
            || (answers
                && a.value
                    .as_deref()
                    .is_some_and(|value| value.split_whitespace().next() == Some("BUNDLE")))
            || a.value.as_deref().is_none_or(|value| {
                value
                    .split_whitespace()
                    .skip(1)
                    .all(|tag| mids.contains(tag))
            })
    });
}

/// The mids of the description's first `a=group:BUNDLE` (RFC 8843 §7.1), in order.
/// The SSRCs a description mentions (`a=ssrc` and `a=ssrc-group` lines, RFC 5576 sections 4.1,
/// 4.2), in any section.
pub(crate) fn described_ssrcs(desc: &SessionDescription) -> HashSet<SSRC> {
    let mut ssrcs = HashSet::new();
    for media in &desc.media_descriptions {
        for a in &media.attributes {
            let Some(value) = a.value.as_deref() else {
                continue;
            };
            match a.key.as_str() {
                "ssrc" => ssrcs.extend(
                    value
                        .split_whitespace()
                        .next()
                        .and_then(|id| id.parse::<SSRC>().ok()),
                ),
                "ssrc-group" => ssrcs.extend(
                    value
                        .split_whitespace()
                        .skip(1)
                        .filter_map(|id| id.parse::<SSRC>().ok()),
                ),
                _ => {}
            }
        }
    }
    ssrcs
}

/// The CNAME each SSRC of a description is declared with (`a=ssrc:<ssrc> cname:<cname>`, RFC
/// 5576 section 6.1), in any section: "This MUST be the CNAME value that the media sender will
/// place in its RTCP SDES packets". An SSRC declared twice keeps its first one (section 6.1:
/// the attribute "MUST NOT occur more than once for the same ssrc-id within a given media
/// stream"). At most [`MAX_REMOTE_CNAMES`](crate::peer_connection::handler::interceptor::MAX_REMOTE_CNAMES).
pub(crate) fn declared_cnames(desc: &SessionDescription) -> HashMap<SSRC, String> {
    use crate::peer_connection::handler::interceptor::MAX_REMOTE_CNAMES;
    let mut cnames = HashMap::new();
    for media in &desc.media_descriptions {
        for a in &media.attributes {
            if a.key != ATTR_KEY_SSRC {
                continue;
            }
            let Some((id, attribute)) = a.value.as_deref().and_then(|v| v.split_once(' ')) else {
                continue;
            };
            let (Ok(ssrc), Some(cname)) = (id.parse::<SSRC>(), attribute.strip_prefix("cname:"))
            else {
                continue;
            };
            if cnames.len() < MAX_REMOTE_CNAMES {
                cnames.entry(ssrc).or_insert_with(|| cname.to_owned());
            }
        }
    }
    cnames
}

/// The decoding dependencies of a description (RFC 5583): for each media section in an
/// `a=group:DDP` group, its mid and its `a=depend` (section 5.2.2). A group whose sections do
/// not all state the same dependency type ("In a DDP group, all media streams MUST have the
/// same type of decoding dependency") is left out, as is a malformed `a=depend`.
pub(crate) fn decoding_dependencies(
    desc: &SessionDescription,
) -> Vec<(String, sdp::attribute::Depend)> {
    use sdp::attribute::{Depend, TypedAttribute};
    let mut out: Vec<(String, Depend)> = vec![];
    for group in desc
        .attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_GROUP)
        .filter_map(|a| a.value.as_deref())
        .filter_map(|value| {
            let mut tokens = value.split_whitespace();
            (tokens.next() == Some("DDP")).then(|| tokens.map(str::to_owned).collect::<Vec<_>>())
        })
    {
        let members: Vec<(String, Depend)> = desc
            .media_descriptions
            .iter()
            .filter_map(|m| {
                let mid = get_mid_value(m)?;
                if !group.contains(mid) {
                    return None;
                }
                let depend = m
                    .attribute(Depend::NAME)
                    .flatten()
                    .and_then(|v| Depend::parse(v).ok())?;
                Some((mid.clone(), depend))
            })
            .collect();
        let mut types = members
            .iter()
            .flat_map(|(_, d)| d.dependencies.iter().map(|dependency| &dependency.typ));
        let first = types.next();
        if first.is_some() && types.all(|t| Some(t) == first) {
            out.extend(members);
        }
    }
    out
}

/// The tokens of an `a=group` line (its semantics first), `None` for another attribute.
fn group_tokens(a: &sdp::description::common::Attribute) -> Option<Vec<&str>> {
    (a.key == ATTR_KEY_GROUP).then(|| {
        a.value
            .as_deref()
            .unwrap_or("")
            .split_whitespace()
            .collect()
    })
}

/// The `a=group` semantics this endpoint acts on: BUNDLE (RFC 9143), lip synchronization
/// (RFC 5888 section 7) and decoding dependency (RFC 5583).
const UNDERSTOOD_GROUP_SEMANTICS: [&str; 3] = ["BUNDLE", "LS", "DDP"];

/// RFC 5888 section 9.3: "If a server receives an offer that contains empty "a=group" lines,
/// it SHOULD add its capabilities also in the form of empty "a=group" lines to its answer."
/// An offer with an `a=group` line that names no identification-tag is answered with an empty
/// `a=group` line for each semantics this endpoint understands and the answer does not use.
pub(crate) fn answer_group_capabilities(
    offer: &SessionDescription,
    answer: &mut SessionDescription,
) {
    let offered_empty = offer
        .attributes
        .iter()
        .filter_map(group_tokens)
        .any(|tokens| tokens.len() == 1);
    if !offered_empty {
        return;
    }
    for semantics in UNDERSTOOD_GROUP_SEMANTICS {
        let used = answer
            .attributes
            .iter()
            .filter_map(group_tokens)
            .any(|tokens| tokens.first() == Some(&semantics));
        if !used {
            answer
                .attributes
                .push(sdp::description::common::Attribute::new(
                    ATTR_KEY_GROUP.to_owned(),
                    Some(semantics.to_owned()),
                ));
        }
    }
}

/// RFC 5583 section 6.1 (with RFC 5888 section 9.2, which it follows) in an answer to
/// `offer`: an answerer that understands DDP keeps the offered dependencies ("The answerer
/// cannot change the dependency relations") for what it accepts. Each offered DDP group is
/// answered with the mids of its sections the answer accepts, when two remain, and each such
/// section with the offer's `a=depend`, restricted to the formats the answer keeps in it and
/// in the sections it depends on; a dependency left with none of the formats it needs is
/// removed with its format's line, as the answerer "MAY remove media Operation Points".
pub(crate) fn answer_decoding_dependencies(
    offer: &SessionDescription,
    answer: &mut SessionDescription,
) {
    use sdp::attribute::{Depend, TypedAttribute};
    let offered = decoding_dependencies(offer);
    if offered.is_empty() {
        return;
    }
    let formats: HashMap<String, Vec<String>> = answer
        .media_descriptions
        .iter()
        .filter(|m| !is_rejected_media(m))
        .filter_map(|m| Some((get_mid_value(m)?.clone(), m.media_name.formats.clone())))
        .collect();
    let groups: Vec<Vec<String>> = offer
        .attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_GROUP)
        .filter_map(|a| a.value.as_deref())
        .filter_map(|value| {
            let mut tokens = value.split_whitespace();
            (tokens.next() == Some("DDP")).then(|| tokens.map(str::to_owned).collect::<Vec<_>>())
        })
        // A group `decoding_dependencies` took (its dependent sections are listed); the
        // sections without `a=depend` (a base layer) are members too.
        .filter(|group| offered.iter().any(|(mid, _)| group.contains(mid)))
        .map(|group| {
            group
                .into_iter()
                .filter(|mid| formats.contains_key(mid))
                .collect::<Vec<_>>()
        })
        .filter(|group| group.len() >= 2)
        .collect();
    for group in &groups {
        answer
            .attributes
            .push(sdp::description::common::Attribute::new(
                ATTR_KEY_GROUP.to_owned(),
                Some(format!("DDP {}", group.join(" "))),
            ));
    }
    for media in &mut answer.media_descriptions {
        let Some(mid) = get_mid_value(media).cloned() else {
            continue;
        };
        if !groups.iter().any(|g| g.contains(&mid)) {
            continue;
        }
        let Some((_, depend)) = offered.iter().find(|(m, _)| *m == mid) else {
            continue;
        };
        let own = &formats[&mid];
        let dependencies: Vec<_> = depend
            .dependencies
            .iter()
            .filter(|d| own.contains(&d.fmt))
            .filter_map(|d| {
                let mut d = d.clone();
                if let Some((on, fmts)) = &mut d.on {
                    let kept = formats.get(on.as_str())?;
                    fmts.retain(|f| kept.contains(f));
                    if fmts.is_empty() || !groups.iter().any(|g| g.contains(on)) {
                        return None;
                    }
                }
                Some(d)
            })
            .collect();
        if !dependencies.is_empty() {
            *media = media
                .clone()
                .with_value_attribute(Depend::NAME.to_owned(), Depend { dependencies }.to_string());
        }
    }
}

/// The lip synchronization groups of a description (`a=group:LS`, RFC 5888 section 7), each
/// its mids in order.
pub(crate) fn ls_groups(desc: &SessionDescription) -> Vec<Vec<String>> {
    desc.attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_GROUP)
        .filter_map(|a| a.value.as_deref())
        .filter_map(|value| {
            let mut tokens = value.split_whitespace();
            (tokens.next() == Some("LS")).then(|| tokens.map(str::to_owned).collect())
        })
        .collect()
}

/// The `a=group:LS` groups of a description being generated (RFC 9429 sections 5.2.1, 5.2.2,
/// 5.3.1). `live` are its accepted RTP sections in order, each with the streams its sender is
/// associated with (empty: none). An offer has a group for each stream more than one of them
/// is associated with, and keeps each group of the most recent answer (`previous`) with the
/// mids still live, when two remain; an answer has, for each offered group (`previous`), the
/// sections of the group that share one stream or have none, when there are two.
fn generated_ls_groups(
    live: &[(String, Vec<String>)],
    previous: &[Vec<String>],
    is_offer: bool,
) -> Vec<Vec<String>> {
    let position = |mid: &String| live.iter().position(|(m, _)| m == mid);
    let ordered = |mut group: Vec<String>| {
        group.sort_by_key(position);
        group.dedup();
        group
    };
    let mut groups: Vec<Vec<String>> = vec![];
    if is_offer {
        for group in previous {
            let kept: Vec<String> = group
                .iter()
                .filter(|mid| position(mid).is_some())
                .cloned()
                .collect();
            if kept.len() >= 2 {
                groups.push(ordered(kept));
            }
        }
        let mut streams: Vec<&String> = vec![];
        for (_, ids) in live {
            for id in ids {
                if !streams.contains(&id) {
                    streams.push(id);
                }
            }
        }
        for stream in streams {
            let members: Vec<String> = live
                .iter()
                .filter(|(_, ids)| ids.contains(stream))
                .map(|(mid, _)| mid.clone())
                .collect();
            if members.len() < 2 {
                continue;
            }
            // A stream's sections join the group of the last answer they are in, if any.
            match groups
                .iter_mut()
                .find(|group| group.iter().any(|mid| members.contains(mid)))
            {
                Some(group) => {
                    let mut joined = group.clone();
                    joined.extend(members);
                    *group = ordered(joined);
                }
                None => groups.push(members),
            }
        }
    } else {
        for group in previous {
            let members: Vec<&(String, Vec<String>)> =
                live.iter().filter(|(mid, _)| group.contains(mid)).collect();
            // The stream most of them share; the first in section order on a tie.
            let mut common: Option<(&String, usize)> = None;
            for (_, ids) in &members {
                for id in ids {
                    let count = members.iter().filter(|(_, i)| i.contains(id)).count();
                    if common.is_none_or(|(_, best)| count > best) {
                        common = Some((id, count));
                    }
                }
            }
            let kept: Vec<String> = members
                .iter()
                .filter(|(_, ids)| ids.is_empty() || common.is_some_and(|(id, _)| ids.contains(id)))
                .map(|(mid, _)| mid.clone())
                .collect();
            if kept.len() >= 2 {
                groups.push(kept);
            }
        }
    }
    groups
}

pub(crate) fn bundle_group_mids(desc: &SessionDescription) -> Vec<&str> {
    desc.attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_GROUP)
        .filter_map(|a| a.value.as_deref())
        .find_map(|value| {
            let mut tokens = value.split_whitespace();
            (tokens.next() == Some("BUNDLE")).then(|| tokens.collect())
        })
        .unwrap_or_default()
}

/// An m-section's ICE credentials: its own `a=ice-ufrag` / `a=ice-pwd`, else the session's
/// (RFC 8839 §5.4 allows both levels).
pub(crate) fn media_ice_credentials<'a>(
    desc: &'a SessionDescription,
    m: &'a MediaDescription,
) -> (Option<&'a str>, Option<&'a str>) {
    let ufrag = m
        .attribute("ice-ufrag")
        .flatten()
        .or_else(|| desc.attribute("ice-ufrag").map(String::as_str));
    let pwd = m
        .attribute("ice-pwd")
        .flatten()
        .or_else(|| desc.attribute("ice-pwd").map(String::as_str));
    (ufrag, pwd)
}

/// Checks ICE credentials against RFC 8839 §5.4: `ice-ufrag` is 4 to 256 ice-chars, `ice-pwd`
/// 22 to 256, an ice-char being ALPHA, DIGIT, "+" or "/" (RFC 8839 §5.1).
fn check_ice_credentials(ufrag: Option<&str>, pwd: Option<&str>) -> Result<()> {
    let valid = |value: &str, min: usize| {
        (min..=256).contains(&value.len())
            && value
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'+' || b == b'/')
    };
    if ufrag.is_some_and(|u| !valid(u, 4)) || pwd.is_some_and(|p| !valid(p, 22)) {
        return Err(Error::ErrSessionDescriptionInvalidIceCredentials);
    }
    Ok(())
}

/// Extracts the credentials and candidates of the ICE transport a remote description sets up.
///
/// This peer connection runs one ICE transport for every m-section, so the description has to
/// name one set of credentials:
///
/// - With a BUNDLE group, that is the offerer-tagged m-section's (the first mid of the group
///   that isn't rejected, RFC 8843 §7.2). The other m-sections of the group may carry their own
///   credentials (an offer under the `balanced` or `max-compat` policy does, JSEP RFC 8829
///   §5.2.1): their transports are discarded once BUNDLE is negotiated (RFC 8843 §7.3.3), so
///   their credentials and candidates aren't used.
/// - Every m-section outside the group must share those credentials; one that doesn't is
///   [`Error::ErrSessionDescriptionConflictingIceUfrag`] /
///   [`Error::ErrSessionDescriptionConflictingIcePwd`]. An inactive one is let through (its
///   credentials are the fallback when every m-section is inactive).
/// - Rejected m-sections set up no transport and are skipped.
///
/// Returns `Ok(None)` when there is no transport to set up: no m-section other than rejected
/// ones, and no session-level credentials (the description of a connection that has nothing to
/// negotiate yet, such as an offer created before any transceiver or data channel was added).
/// Why a remote `candidate` line that follows the grammar is to be ignored, rather than
/// refuse its description (RFC 8839 section 5.1): its address is a fully qualified domain
/// name ("An agent processing remote candidates MUST ignore "candidate" lines that include
/// candidates with FQDNs"; a host candidate's `<name>.local` is resolved by mDNS,
/// draft-ietf-mmusic-mdns-ice-candidates section 3.2.1, and a `.local` name of more than one
/// "." or on another candidate type is an FQDN like any other), or its transport or candidate type is one this agent does not know (both are
/// extensible tokens in the grammar). `None`: the line is parsed as usual, and a line that does
/// not follow the grammar still refuses the description.
pub(crate) fn ignored_candidate_line(value: &str) -> Option<&'static str> {
    let fields: Vec<&str> = value.split_ascii_whitespace().collect();
    if fields.len() < 8 {
        return None;
    }
    let (transport, address, typ) = (fields[2], fields[4], fields[7]);
    if !transport.eq_ignore_ascii_case("udp") && !transport.eq_ignore_ascii_case("tcp") {
        return Some("an unknown transport");
    }
    if !matches!(typ, "host" | "srflx" | "prflx" | "relay") {
        return Some("an unknown candidate type");
    }
    let is_ip = address.parse::<std::net::IpAddr>().is_ok();
    // draft-ietf-mmusic-mdns-ice-candidates section 3.2.1: only an address that ends with
    // ".local" and has no other "." is resolved by mDNS (step 1 sends the rest to RFC 8445
    // processing, where an FQDN is ignored), and only a host candidate carries one (section
    // 3.1.2.2 hides host addresses alone).
    let mdns_name = typ == "host"
        && address.to_ascii_lowercase().ends_with(".local")
        && address.matches('.').count() == 1;
    if !is_ip && !mdns_name {
        let fqdn = address.split('.').all(|label| {
            !label.is_empty()
                && label
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-')
        });
        if fqdn {
            return Some("its address is a domain name (FQDN)");
        }
    }
    None
}

pub(crate) fn extract_ice_details(desc: &SessionDescription) -> Result<Option<RemoteIceDetails>> {
    let bundle = bundle_group_mids(desc);
    let bundle_set: HashSet<&str> = bundle.iter().copied().collect();
    let in_bundle = |m: &MediaDescription| {
        get_mid_value(m).is_some_and(|mid| bundle_set.contains(mid.as_str()))
    };
    // The first m-section that isn't rejected, for each mid: a lookup per bundle mid instead of
    // a scan of every m-section.
    let mut usable_by_mid: HashMap<&str, &MediaDescription> = HashMap::new();
    for m in &desc.media_descriptions {
        if let Some(mid) = get_mid_value(m)
            && !is_rejected_media(m)
        {
            usable_by_mid.entry(mid.as_str()).or_insert(m);
        }
    }
    let tagged = bundle
        .iter()
        .find_map(|mid| usable_by_mid.get(mid).copied());

    // Backup ufrag/pwd is the first inactive credentials found, for the corner case where all
    // media lines/transceivers are set to inactive.
    let mut backup_ufrag = None;
    let mut backup_pwd = None;

    let (mut remote_ufrag, mut remote_pwd) = match tagged {
        Some(m) => media_ice_credentials(desc, m),
        None => (
            desc.attribute("ice-ufrag").map(String::as_str),
            desc.attribute("ice-pwd").map(String::as_str),
        ),
    };

    let mut has_transport = remote_ufrag.is_some() || remote_pwd.is_some() || tagged.is_some();
    let mut transport_media = vec![];
    for m in &desc.media_descriptions {
        if is_rejected_media(m) {
            continue;
        }
        has_transport = true;
        let (ufrag, pwd) = media_ice_credentials(desc, m);
        check_ice_credentials(ufrag, pwd)?;

        if tagged.is_some() && in_bundle(m) {
            // Part of the tagged m-section's transport only when it says so with the same
            // credentials; otherwise its own transport, which BUNDLE replaces.
            if (ufrag.is_none() || ufrag == remote_ufrag) && (pwd.is_none() || pwd == remote_pwd) {
                transport_media.push(m);
            }
            continue;
        }

        if m.attribute(ATTR_KEY_INACTIVE).is_some() {
            if backup_ufrag.is_none() {
                backup_ufrag = ufrag;
            }
            if backup_pwd.is_none() {
                backup_pwd = pwd;
            }
            continue;
        }

        if remote_ufrag.is_none() {
            remote_ufrag = ufrag;
        }
        if remote_pwd.is_none() {
            remote_pwd = pwd;
        }

        if ufrag.is_some() && ufrag != remote_ufrag {
            return Err(Error::ErrSessionDescriptionConflictingIceUfrag);
        }
        if pwd.is_some() && pwd != remote_pwd {
            return Err(Error::ErrSessionDescriptionConflictingIcePwd);
        }
        transport_media.push(m);
    }

    if !has_transport {
        return Ok(None);
    }
    check_ice_credentials(remote_ufrag, remote_pwd)?;

    let remote_ufrag = remote_ufrag
        .or(backup_ufrag)
        .ok_or(Error::ErrSessionDescriptionMissingIceUfrag)?;
    let remote_pwd = remote_pwd
        .or(backup_pwd)
        .ok_or(Error::ErrSessionDescriptionMissingIcePwd)?;

    let mut candidates = vec![];
    for m in transport_media {
        for a in &m.attributes {
            if a.is_ice_candidate()
                && let Some(value) = &a.value
            {
                if let Some(reason) = ignored_candidate_line(value) {
                    log::warn!("ignoring remote candidate line {value:?}: {reason}");
                    continue;
                }
                candidates.push(unmarshal_candidate(value)?);
            }
        }
    }

    Ok(Some(RemoteIceDetails {
        ufrag: remote_ufrag.to_owned(),
        pwd: remote_pwd.to_owned(),
        candidates,
    }))
}

/// RFC 8839 section 4.4.2.1: "If any of the SDP attributes [`ice-options`, `ice-pacing`,
/// `ice-lite`] have been modified in a subsequent offer that is not used to request an ICE
/// restart, the answerer MUST reject the offer." `previous` is the current remote
/// description; `offer` keeps its ICE credentials (no restart). The attributes are read at
/// session level and in the first live section, where this engine and browsers write them.
pub(crate) fn check_ice_attributes_unchanged(
    previous: &SessionDescription,
    offer: &SessionDescription,
) -> Result<()> {
    fn of(desc: &SessionDescription) -> (bool, Vec<String>, Option<String>) {
        let first = desc
            .media_descriptions
            .iter()
            .find(|m| !is_rejected_media(m));
        let value = |key: &str| {
            desc.attribute(key)
                .map(String::as_str)
                .or_else(|| first.and_then(|m| m.attribute(key).flatten()))
                .map(str::to_owned)
        };
        let mut options: Vec<String> = value(ATTR_KEY_ICE_OPTIONS)
            .unwrap_or_default()
            .split_ascii_whitespace()
            .map(str::to_owned)
            .collect();
        options.sort();
        (is_lite_set(desc), options, value(ATTR_KEY_ICE_PACING))
    }
    let (before, after) = (of(previous), of(offer));
    if before != after {
        return Err(Error::SdpInvalidValue(format!(
            "an offer without an ICE restart changed ice-lite / ice-options / ice-pacing \
             ({before:?} to {after:?}; RFC 8839 section 4.4.2.1)"
        )));
    }
    Ok(())
}

pub(crate) fn is_lite_set(desc: &SessionDescription) -> bool {
    for a in &desc.attributes {
        if a.key.trim() == ATTR_KEY_ICELITE {
            return true;
        }
    }
    false
}

pub(crate) trait MediaDescriptionExt {
    /// Reports whether `self` is the WebRTC SCTP data channel m-line, as opposed to some
    /// other RTP-carried media that also uses the SDP media name `"application"`.
    fn is_webrtc_datachannel(&self) -> bool;
}

impl MediaDescriptionExt for MediaDescription {
    /// RFC 8841 section 4.4.2: media `application`, proto `UDP/DTLS/SCTP` or `TCP/DTLS/SCTP`,
    /// and the one fmt `webrtc-datachannel`; or the `DTLS/SCTP <sctp-port>` line with
    /// `a=sctpmap:<sctp-port> webrtc-datachannel` of the drafts before the RFC, which RFC 9429
    /// section 5.1.2 has a JSEP endpoint receive "for backwards compatibility"
    /// ([`is_legacy_data_section`]). Any other `m=application` line is not a data channel
    /// section.
    fn is_webrtc_datachannel(&self) -> bool {
        self.media_name.media == MEDIA_SECTION_APPLICATION
            && (self.media_name.formats == ["webrtc-datachannel"]
                && (self.media_name.protos == ["UDP", "DTLS", "SCTP"]
                    || self.media_name.protos == ["TCP", "DTLS", "SCTP"])
                || legacy_sctp_port(self).is_some())
    }
}

/// The SCTP port of a data section in the form of the drafts before RFC 8841: `m=application
/// <port> DTLS/SCTP <sctp-port>` with `a=sctpmap:<sctp-port> webrtc-datachannel <streams>`
/// (draft-ietf-mmusic-sctp-sdp-05). `None` for any other line.
pub(crate) fn legacy_sctp_port(media: &MediaDescription) -> Option<u16> {
    if media.media_name.media != MEDIA_SECTION_APPLICATION
        || media.media_name.protos != ["DTLS", "SCTP"]
    {
        return None;
    }
    let [format] = media.media_name.formats.as_slice() else {
        return None;
    };
    let port = format.parse::<u16>().ok()?;
    media
        .attributes
        .iter()
        .filter(|a| a.key == "sctpmap")
        .filter_map(|a| a.value.as_deref())
        .any(|value| {
            let mut fields = value.split_ascii_whitespace();
            fields.next() == Some(format.as_str()) && fields.next() == Some("webrtc-datachannel")
        })
        .then_some(port)
}

/// Turns this endpoint's data section `media` into the form of the drafts before RFC 8841,
/// the profile of an offer that used it (RFC 9429 section 5.3.1: the answer's profile "MUST
/// exactly match the profile provided in the offer"): `DTLS/SCTP <sctp-port>` with
/// `a=sctpmap:<sctp-port> webrtc-datachannel 65535` in place of `a=sctp-port`.
pub(crate) fn into_legacy_data_section(media: &mut MediaDescription) {
    let Some(port) = media
        .attributes
        .iter()
        .find(|a| a.key == "sctp-port")
        .and_then(|a| a.value.clone())
    else {
        return;
    };
    media.media_name.protos = vec!["DTLS".to_owned(), "SCTP".to_owned()];
    media.media_name.formats = vec![port.clone()];
    for attribute in &mut media.attributes {
        if attribute.key == "sctp-port" {
            attribute.key = "sctpmap".to_owned();
            attribute.value = Some(format!("{port} webrtc-datachannel 65535"));
        }
    }
}

/// Whether `media` is an `m=application` line that is neither a data channel section
/// (RFC 8841, or the drafts before it) nor application media over RTP, or an `m=audio` /
/// `m=video` line whose protocol is not RTP (RFC 8866 section 5.14: "the interpretation of
/// the media format depends on the value of the <proto> sub-field", so the formats of
/// `m=audio 9 udptl t38` are no payload types): a protocol this endpoint does not know. It is
/// answered like a media type this endpoint does not know, rejected with its own m= line, and
/// gets no transceiver. An audio or video section built in code without a protocol (every
/// parsed m= line has one) is read as RTP.
pub(crate) fn is_unknown_media_protocol(media_desc: &MediaDescription) -> bool {
    let rtp = media_desc
        .media_name
        .protos
        .iter()
        .any(|proto| proto == "RTP");
    match media_desc.media_name.media.as_str() {
        MEDIA_SECTION_APPLICATION => !media_desc.is_webrtc_datachannel() && !rtp,
        "audio" | "video" => !rtp && !media_desc.media_name.protos.is_empty(),
        _ => false,
    }
}

/// The `a=sctp-port` of a data channel section (RFC 8841 section 5): `Ok(None)` when the
/// attribute is absent, an error when its value is not `1*5(DIGIT)` in 0..=65535.
///
/// Leading zeroes are taken: section 5.2 forbids writing them, not reading them.
pub(crate) fn get_application_media_section_sctp_port(
    media_desc: &MediaDescription,
) -> Result<Option<u16>> {
    let Some(attribute) = media_desc
        .attributes
        .iter()
        .find(|attr| attr.key == "sctp-port")
    else {
        // The drafts before RFC 8841 name the port in the fmt and `a=sctpmap`.
        return Ok(legacy_sctp_port(media_desc));
    };
    let value = attribute.value.as_deref().unwrap_or_default();
    if value.is_empty() || value.len() > 5 || !value.bytes().all(|b| b.is_ascii_digit()) {
        return Err(Error::ErrSDPSctpPortInvalid);
    }
    value
        .parse::<u16>()
        .map(Some)
        .map_err(|_| Error::ErrSDPSctpPortInvalid)
}

/// RFC 9429 sections 5.2.3.2 and 5.3.3.1, `VoiceActivityDetection`: in each live audio
/// section of `d`, the comfort noise formats (`CN`, RFC 3389) are kept when `vad` is true and
/// removed with their lines otherwise, and Opus states `usedtx=1` or `usedtx=0` (RFC 7587
/// section 7: whether this endpoint wants DTX in what it receives). An answer (`offer` is the
/// remote offer) keeps silence suppression only where the offer's section of the same mid
/// indicated it: "if support for silence suppression was not indicated in the offer, ... the
/// answer MUST be generated as if VoiceActivityDetection was set to "false"", per codec.
pub(crate) fn apply_voice_activity_detection(
    d: &mut SessionDescription,
    vad: bool,
    offer: Option<&SessionDescription>,
) {
    fn payload_types(media: &MediaDescription, codec: &str) -> Vec<String> {
        media
            .attributes
            .iter()
            .filter(|a| a.key == "rtpmap")
            .filter_map(|a| a.value.as_deref())
            .filter_map(|value| {
                let (pt, encoding) = value.split_once(' ')?;
                let name = encoding.split('/').next()?;
                name.eq_ignore_ascii_case(codec).then(|| pt.to_owned())
            })
            .collect()
    }
    fn format_of(value: &str) -> &str {
        value.split_once(' ').map_or(value, |(format, _)| format)
    }
    fn fmtp_params(media: &MediaDescription, pt: &str) -> Option<String> {
        media
            .attributes
            .iter()
            .filter(|a| a.key == "fmtp")
            .filter_map(|a| a.value.as_deref())
            .find_map(|value| {
                let (format, params) = value.split_once(' ')?;
                (format == pt).then(|| params.to_owned())
            })
    }
    fn is_usedtx(parameter: &str) -> bool {
        parameter
            .split_once('=')
            .is_some_and(|(k, _)| k.trim().eq_ignore_ascii_case("usedtx"))
    }
    fn wants_dtx(params: &str) -> bool {
        params
            .split(';')
            .any(|p| is_usedtx(p.trim()) && p.split_once('=').is_some_and(|(_, v)| v.trim() == "1"))
    }
    for media in &mut d.media_descriptions {
        // A bundle-only section of an offer (port zero, RFC 9143 section 7.2) is an audio
        // section like the others; a rejected one is left as it is.
        if media.media_name.media != "audio" || is_rejected_media(media) {
            continue;
        }
        let offered = offer.and_then(|offer| {
            let mid = get_mid_value(media)?;
            offer
                .media_descriptions
                .iter()
                .find(|m| get_mid_value(m).is_some_and(|m| m == mid))
        });
        let offered_cn = offered.is_none_or(|o| !payload_types(o, "CN").is_empty());
        let offered_dtx = offered.is_none_or(|o| {
            payload_types(o, "opus")
                .iter()
                .any(|pt| fmtp_params(o, pt).is_some_and(|p| wants_dtx(&p)))
        });
        if !(vad && offered_cn) {
            let cn = payload_types(media, "CN");
            media.media_name.formats.retain(|f| !cn.contains(f));
            media.attributes.retain(|a| {
                !(matches!(a.key.as_str(), "rtpmap" | "fmtp" | "rtcp-fb")
                    && a.value
                        .as_deref()
                        .is_some_and(|v| cn.iter().any(|pt| format_of(v) == pt.as_str())))
            });
        }
        let usedtx = if vad && offered_dtx { "1" } else { "0" };
        for pt in payload_types(media, "opus") {
            let mut parameters: Vec<String> = fmtp_params(media, &pt)
                .unwrap_or_default()
                .split(';')
                .map(str::trim)
                .filter(|p| !p.is_empty() && !is_usedtx(p))
                .map(str::to_owned)
                .collect();
            parameters.push(format!("usedtx={usedtx}"));
            let value = format!("{pt} {}", parameters.join(";"));
            match media
                .attributes
                .iter_mut()
                .find(|a| a.key == "fmtp" && a.value.as_deref().is_some_and(|v| format_of(v) == pt))
            {
                Some(attribute) => attribute.value = Some(value),
                None => media
                    .attributes
                    .push(sdp::description::common::Attribute::new(
                        "fmtp".to_owned(),
                        Some(value),
                    )),
            }
        }
    }
}

/// RFC 9429 section 5.10: "If any RTX or FEC format ... is present, but the primary format it
/// is associated with is not present, an error MUST be returned": an `a=fmtp:<pt> apt=<x>` of a
/// live RTP section whose `x` is not one of the section's formats (RFC 4588 section 8.6).
/// A primary that is present but not supported is not an error: the RTX format is then
/// ignored (`MediaEngine::match_remote_codec`).
pub(crate) fn check_repair_primaries(desc: &SessionDescription) -> Result<()> {
    for media in &desc.media_descriptions {
        if is_rejected_media(media) || media.is_webrtc_datachannel() {
            continue;
        }
        let formats = &media.media_name.formats;
        for attribute in media.attributes.iter().filter(|a| a.key == "fmtp") {
            let Some(value) = attribute.value.as_deref() else {
                continue;
            };
            let Some((pt, parameters)) = value.split_once(' ') else {
                continue;
            };
            if !formats.iter().any(|f| f == pt) {
                continue;
            }
            for parameter in parameters.split(';') {
                if let Some((key, apt)) = parameter.trim().split_once('=')
                    && key.trim().eq_ignore_ascii_case("apt")
                    && !formats.iter().any(|f| f == apt.trim())
                {
                    return Err(Error::SdpInvalidValue(format!(
                        "a=fmtp:{value}: the associated payload type is not on the m= line \
                         (RFC 9429 section 5.10)"
                    )));
                }
            }
        }
    }
    Ok(())
}

/// Checks the data channel section of a remote description, if it has one that is not
/// rejected, and returns its `a=sctp-port`.
///
/// RFC 8841 section 5.1: "No default value is defined for the SDP 'sctp-port' attribute.
/// Therefore, if the attribute is not present, the associated 'm=' line MUST be considered
/// invalid." A description with such a line, or with a port that is not one, is refused; it
/// used to be taken with port 5000 assumed. A port of 0 is valid: it asks for no association
/// (section 9.3).
pub(crate) fn validate_application_media_section(desc: &SessionDescription) -> Result<()> {
    match get_application_media(desc) {
        Some(media) if !is_rejected_application_media(media) => {
            match get_application_media_section_sctp_port(media)? {
                Some(_) => Ok(()),
                None => Err(Error::ErrSDPSctpPortInvalid),
            }
        }
        _ => Ok(()),
    }
}

/// A data channel section with port zero and no `a=bundle-only`: rejected (RFC 3264 section
/// 6) or, in an offer, closed (RFC 8841 section 10.5). A zero port with `a=bundle-only` is a
/// bundled section of an offer, not a rejected one (RFC 9143 sections 7.2 and 13): every
/// section but the first of a `max-bundle` initial offer (RFC 9429 sections 5.2.1 and 7.2),
/// so the data section beside media. An answer never carries `a=bundle-only` (RFC 9429
/// section 5.3.1; a remote answer's is discarded, `discard_stray_bundle_only`), so a zero port
/// there is a rejection. 0.2.0 read the zero port alone and took the data section of such an
/// offer for a rejected one: no association, the channels failed.
fn is_rejected_application_media(media_desc: &MediaDescription) -> bool {
    is_rejected_media(media_desc)
}

/// What an offer/answer pair negotiated for the SCTP association (RFC 8841 section 10).
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub(crate) enum SctpNegotiation {
    /// One of the descriptions has no data channel section: nothing was negotiated about
    /// SCTP, and what exists stays as it is.
    NoSection,
    /// The data section is rejected, m= port zero in the offer or in the answer (sections
    /// 10.3, 10.4 and 10.5): no association is established, and one that exists is closed.
    Rejected,
    /// One side's `a=sctp-port` is zero (section 9.3): no association is established, and
    /// one that exists is closed; DTLS is not affected.
    PortZero,
    /// An association between these two SCTP ports, with the largest message the peer
    /// takes (0: any size).
    Association {
        local_port: u16,
        remote_port: u16,
        remote_max_message_size: u32,
    },
}

/// Reads [`SctpNegotiation`] off the two descriptions of a completed exchange.
pub(crate) fn negotiated_sctp(
    local: &SessionDescription,
    remote: &SessionDescription,
) -> SctpNegotiation {
    let (Some(local), Some(remote)) = (get_application_media(local), get_application_media(remote))
    else {
        return SctpNegotiation::NoSection;
    };
    if is_rejected_application_media(local) || is_rejected_application_media(remote) {
        return SctpNegotiation::Rejected;
    }
    // A local section always has the attribute, and a remote one was checked when the
    // description was applied; one without is no association either.
    let port = |media| {
        get_application_media_section_sctp_port(media)
            .ok()
            .flatten()
            .unwrap_or(0)
    };
    match (port(local), port(remote)) {
        (0, _) | (_, 0) => SctpNegotiation::PortZero,
        (local_port, remote_port) => SctpNegotiation::Association {
            local_port,
            remote_port,
            // RFC 8841 section 6.1: "If the SDP 'max-message-size' attribute is not present,
            // the default value is 64K."
            remote_max_message_size: get_application_media_section_max_message_size(remote)
                .unwrap_or(crate::peer_connection::configuration::setting_engine::SctpMaxMessageSize::DEFAULT_MESSAGE_SIZE),
        },
    }
}

/// The `a=max-message-size` of a data channel section (RFC 8841 section 6): the largest
/// message its sender takes, 0 for any size, `None` when absent (the default is then 64K).
/// A value above what 32 bits hold is as good as no limit; one that is not a number is taken
/// as absent, the smaller and so the safe reading.
pub(crate) fn get_application_media_section_max_message_size(
    media_desc: &MediaDescription,
) -> Option<u32> {
    if !media_desc.is_webrtc_datachannel() {
        return None;
    }
    let value = media_desc.attribute(ATTR_KEY_MAX_MESSAGE_SIZE)??;
    if value.is_empty() || !value.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    Some(value.parse::<u32>().unwrap_or(0))
}

pub(crate) fn get_by_mid<'a>(
    search_mid: &str,
    desc: &'a session_description::RTCSessionDescription,
) -> Option<&'a MediaDescription> {
    if let Some(parsed) = &desc.parsed {
        for m in &parsed.media_descriptions {
            if let Some(mid) = m.attribute(ATTR_KEY_MID).flatten()
                && mid == search_mid
            {
                return Some(m);
            }
        }
    }
    None
}

/// The data channel section of a description: the one in use if it has several (an offer
/// made after a data section was rejected carries the rejected one and a new one).
pub(crate) fn get_application_media(desc: &SessionDescription) -> Option<&MediaDescription> {
    let mut sections = desc
        .media_descriptions
        .iter()
        .filter(|media_description| media_description.is_webrtc_datachannel());
    let first = sections.next()?;
    if !is_rejected_application_media(first) {
        return Some(first);
    }
    sections
        .find(|media_description| !is_rejected_application_media(media_description))
        .or(Some(first))
}

/// have_data_channel return MediaDescription with MediaName equal application
pub(crate) fn have_data_channel(
    desc: &session_description::RTCSessionDescription,
) -> Option<&MediaDescription> {
    get_application_media(desc.parsed.as_ref()?)
}

const ATTR_KEY_RTCP_FB: &str = "rtcp-fb";

/// One feedback value of an `a=rtcp-fb` line, the payload type removed: the type (`nack`,
/// `ccm`, `ack`, `goog-remb`, ...) and everything after it as the parameter (`pli`, `fir`,
/// `ccfb`, `100` of `trr-int 100`). `None` for an empty value.
fn parse_rtcp_feedback(value: &str) -> Option<RTCPFeedback> {
    let mut tokens = value.split_whitespace();
    let typ = tokens.next()?.to_owned();
    Some(RTCPFeedback {
        typ,
        parameter: tokens.collect::<Vec<_>>().join(" "),
    })
}

/// The payload types the formats an answer adds after the offered ones take (RFC 9429
/// section 5.3.1), by (SFrame numbering, kind, the format's own payload type), worked out once
/// for the whole answer so that every section numbers a format alike. A format keeps its own
/// number unless the offer uses that number for another format anywhere (in a BUNDLE group one
/// payload type has one configuration, RFC 9143 section 9.1.1), or an earlier description of
/// the session gave it another format (RFC 3264 section 8.3.2: the mapping "MUST NOT change
/// for the duration of a session"); then it takes the next dynamic payload type no offered,
/// registered or SFrame format uses, no earlier description used and no format before it
/// took. A format with nothing left is not added.
fn answer_payload_types(
    media_engine: &MediaEngine,
    media_sections: &[MediaSection],
) -> HashMap<(bool, RtpCodecKind, u8), u8> {
    let mut offered: HashMap<u8, RTCRtpCodec> = HashMap::new();
    for codec in media_sections
        .iter()
        .filter_map(|m| m.offered_codecs.as_ref())
        .flatten()
    {
        offered
            .entry(codec.payload_type)
            .or_insert_with(|| codec.rtp_codec.clone());
    }
    let kinds = [RtpCodecKind::Audio, RtpCodecKind::Video];
    let candidates: Vec<(bool, RtpCodecKind, RTCRtpCodecParameters)> = kinds
        .iter()
        .flat_map(|&kind| {
            media_engine
                .registered_codecs_by_kind(kind)
                .iter()
                .cloned()
                .map(move |codec| (false, kind, codec))
        })
        .chain(kinds.iter().flat_map(|&kind| {
            media_engine
                .codecs_for_section(kind, true)
                .into_iter()
                .map(move |codec| (true, kind, codec))
        }))
        .collect();
    let mut taken: HashSet<u8> = offered.keys().copied().collect();
    taken.extend(candidates.iter().map(|(_, _, codec)| codec.payload_type));
    taken.extend(media_engine.sframe_payload_types.iter().copied());
    taken.extend(media_engine.payload_type_history.keys().copied());
    let mut free = (96..=127u8).filter(|pt| !taken.contains(pt));
    let mut numbers = HashMap::new();
    for (sframe, kind, codec) in candidates {
        let conflicting = offered.get(&codec.payload_type).is_some_and(|offered| {
            codec_parameters_fuzzy_search(offered, std::slice::from_ref(&codec)).1
                != CodecMatch::Exact
        }) || media_engine
            .payload_type_means_another_format(codec.payload_type, &codec);
        let number = if conflicting {
            // A number an earlier description already gave this very format, when the offer
            // does not use it for another one; else a new one.
            media_engine
                .payload_type_history
                .iter()
                .filter(|(pt, earlier)| {
                    !offered.contains_key(pt)
                        && crate::peer_connection::configuration::media_engine::is_same_codec(
                            earlier,
                            &codec.rtp_codec,
                        )
                })
                .map(|(pt, _)| *pt)
                .min()
                .or_else(|| free.next())
        } else {
            Some(codec.payload_type)
        };
        if let Some(number) = number {
            numbers.insert((sframe, kind, codec.payload_type), number);
        }
    }
    numbers
}

/// The formats of `codecs` (an answer's, in its order) that `offered` has
/// (`SettingEngineBuilder::with_answer_offered_formats_only`), matched as a remote description
/// is (`RTCRtpTransceiverInternal::match_remote_codecs`): an exact match, or a match by name
/// for a format whose parameters are not its configuration. A repair format stays only with
/// what it repairs: an RTX format when the offer has RTX and its `apt` names a kept format, a
/// RED format when the formats its fmtp line names are kept (or it names none), a FEC format
/// when a media format is kept.
fn offered_formats_only(
    codecs: Vec<RTCRtpCodecParameters>,
    offered: &[RTCRtpCodecParameters],
) -> Vec<RTCRtpCodecParameters> {
    use crate::peer_connection::configuration::media_engine::{
        has_symmetric_configuration, red_block_payload_types,
    };
    use crate::rtp_transceiver::rtp_sender::rtp_codec::parse_rtx_apt;
    let is_offered = |codec: &RTCRtpCodecParameters| match codec_parameters_search(
        &codec.rtp_codec,
        Some(codec.payload_type),
        offered,
    ) {
        (_, CodecMatch::Exact) => true,
        (found, CodecMatch::Partial) => {
            !has_symmetric_configuration(&codec.rtp_codec)
                || found.rtp_codec.sdp_fmtp_line.trim().is_empty()
        }
        (_, CodecMatch::None) => false,
    };
    let offer_has_rtx = offered
        .iter()
        .any(|codec| repair_family(&codec.rtp_codec) == "rtx");
    let mut kept: Vec<RTCRtpCodecParameters> = codecs
        .into_iter()
        .filter(|codec| repair_family(&codec.rtp_codec) == "rtx" || is_offered(codec))
        .collect();
    let media: HashSet<PayloadType> = kept
        .iter()
        .filter(|codec| repair_family(&codec.rtp_codec).is_empty())
        .map(|codec| codec.payload_type)
        .collect();
    kept.retain(|codec| match repair_family(&codec.rtp_codec) {
        "" => true,
        "red" => red_block_payload_types(&codec.rtp_codec.sdp_fmtp_line)
            .is_none_or(|blocks| blocks.iter().all(|block| media.contains(block))),
        "ulpfec" | "flexfec" => !media.is_empty(),
        _ => true,
    });
    // RTX: its `apt` names a kept primary (a media format, or a kept RED format).
    let primaries: HashSet<PayloadType> = kept
        .iter()
        .filter(|codec| repair_family(&codec.rtp_codec) != "rtx")
        .map(|codec| codec.payload_type)
        .collect();
    kept.retain(|codec| {
        repair_family(&codec.rtp_codec) != "rtx"
            || (offer_has_rtx
                && parse_rtx_apt(&codec.rtp_codec.sdp_fmtp_line)
                    .is_some_and(|apt| primaries.contains(&apt)))
    });
    kept
}

pub(crate) fn codecs_from_media_description(
    m: &MediaDescription,
) -> Result<Vec<RTCRtpCodecParameters>> {
    let codecs = m.codecs();
    // Feedback for the wildcard payload type applies to every format of the section (RFC 4585
    // section 4.2: "'*' ... indicates that the RTCP feedback attribute applies to all payload
    // types"); RFC 8888 section 6 has `ack ccfb` signalled only that way.
    let wildcard_feedback: Vec<RTCPFeedback> = m
        .attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_RTCP_FB)
        .filter_map(|a| a.value.as_deref())
        .filter_map(|value| value.strip_prefix("* "))
        .filter_map(parse_rtcp_feedback)
        .collect();
    // RFC 3611 section 5.1: `a=rtcp-xr:rcvr-rtt=<mode>` asks for receiver reference times,
    // what libwebrtc's `a=rtcp-fb:<pt> rrtr` asks for: taken as that feedback for each
    // format, marked as coming from here. A section whose `a=rtcp-xr` does not list it wants
    // no such blocks (section 5.1: "it SHOULD NOT send XR blocks other than those listed"),
    // whatever its `a=rtcp-fb` lines say.
    let rtcp_xr = media_rtcp_xr(m);
    // The `rcvr-rtt` format in full (`rcvr-rtt=<mode>[:<max size>]`): the mode and the
    // maximum block size reach the interceptor as the parameter of the `rrtr` entry (RFC 3611
    // section 5.1: DLRR blocks within the signalled maximum).
    let xr_rrtr = rtcp_xr
        .as_ref()
        .map(|formats| formats.iter().find(|f| is_rcvr_rtt(f)).cloned());

    let mut out = vec![];
    // A payload type listed more than once on the m= line describes one codec: keep its first
    // position and skip the repeats, so the output is at most one entry per payload type.
    let mut seen = [false; 256];
    for payload_str in &m.media_name.formats {
        let payload_type: PayloadType = payload_str.parse::<u8>()?;
        if std::mem::replace(&mut seen[payload_type as usize], true) {
            continue;
        }
        // RFC 5761 section 4: "RTP payload types in the range 64-95 MUST NOT be used" where
        // RTP and RTCP share a port, as they always do here. A format numbered so is one this
        // endpoint cannot receive or send: left out, like a format it does not know.
        if is_rtcp_conflicting_payload_type(payload_type) {
            continue;
        }
        // A payload type with no `a=rtpmap` (only `a=fmtp` / `a=rtcp-fb`
        // lines, or none) is RFC 3551's static assignment for audio, else a
        // format this description doesn't define: RFC 9429 section 5.3.1 and
        // 5.8 ignore a format the endpoint doesn't know, rather than
        // rejecting the whole description.
        let static_codec;
        let codec = match codecs.get(&payload_type).filter(|c| !c.name.is_empty()) {
            Some(codec) => codec,
            None => {
                let Some((name, clock_rate, channels)) =
                    static_payload_type(&m.media_name.media, payload_type)
                else {
                    continue;
                };
                let defined = codecs.get(&payload_type);
                static_codec = sdp::util::Codec {
                    payload_type,
                    name: name.to_owned(),
                    clock_rate,
                    encoding_parameters: channels.map(|n| n.to_string()).unwrap_or_default(),
                    fmtp: defined.map(|c| c.fmtp.clone()).unwrap_or_default(),
                    rtcp_feedback: defined.map(|c| c.rtcp_feedback.clone()).unwrap_or_default(),
                };
                &static_codec
            }
        };

        let channels = codec.encoding_parameters.parse::<u16>().unwrap_or(0);

        let mut feedback: Vec<RTCPFeedback> = codec
            .rtcp_feedback
            .iter()
            .filter_map(|raw| parse_rtcp_feedback(raw))
            .collect();
        // RFC 7728 section 9: a `*` line with `pause` applies "to all listed payload types
        // that do not have an explicit "pause" specification".
        let is_pause = |f: &RTCPFeedback| {
            f.typ == crate::rtp_transceiver::rtp_sender::TYPE_RTCP_FB_CCM
                && interceptor::PauseCapability::parse(&f.parameter).is_some()
        };
        let explicit_pause = feedback.iter().any(is_pause);
        for entry in &wildcard_feedback {
            if !feedback.contains(entry) && !(explicit_pause && is_pause(entry)) {
                feedback.push(entry.clone());
            }
        }
        match &xr_rrtr {
            Some(Some(format)) => feedback.push(RTCPFeedback {
                typ: interceptor::RTCP_FB_RRTR.to_owned(),
                parameter: format.clone(),
            }),
            Some(None) => feedback.retain(|f| f.typ != interceptor::RTCP_FB_RRTR),
            None => {}
        }
        // The other `xr-format`s of `a=rtcp-xr` (RFC 3611 section 5.1: `pkt-loss-rle`,
        // `stat-summary`, `voip-metrics`, ...): an `xr` entry each, the format in full as the
        // parameter, which the XR generator of the interceptor chain is driven by.
        for format in rtcp_xr.iter().flatten().filter(|f| !is_rcvr_rtt(f)) {
            let entry = RTCPFeedback {
                typ: RTCP_FB_XR.to_owned(),
                parameter: format.clone(),
            };
            if !feedback.contains(&entry) {
                feedback.push(entry);
            }
        }

        out.push(RTCRtpCodecParameters {
            rtp_codec: RTCRtpCodec {
                mime_type: m.media_name.media.clone() + "/" + codec.name.as_str(),
                clock_rate: codec.clock_rate,
                channels,
                sdp_fmtp_line: codec.fmtp.clone(),
                rtcp_feedback: feedback,
            },
            payload_type,
        })
    }

    Ok(out)
}

/// The m= line of a section whose media type this endpoint doesn't know (not audio or
/// video, or audio or video over a protocol that is not RTP), for a rejection that
/// reproduces it. An `m=application` line is reproduced too:
/// a data channel section keeps its proto (`TCP/DTLS/SCTP` stays that), and one that is not
/// a data channel section (the pre-RFC `DTLS/SCTP 5000` form, application media over RTP)
/// is not answered as if it had been one.
pub(crate) fn unknown_media_name(media: &MediaDescription) -> Option<MediaName> {
    let kind = media.media_name.media.as_str();
    if matches!(kind, "audio" | "video") && !is_unknown_media_protocol(media) {
        return None;
    }
    let mut name = media.media_name.clone();
    if name.formats.is_empty() {
        name.formats.push("0".to_owned());
    }
    Some(name)
}

/// RFC 3551 section 6's static payload types of a section of `media` (`audio`: Table 4,
/// `video`: Table 5): encoding name, clock rate and, where the table gives it, the number of
/// channels. RFC 3551 section 3: a static payload type means its encoding without an
/// `a=rtpmap` line. A type of the other media kind's table is not one of this section's.
fn static_payload_type(
    media: &str,
    payload_type: PayloadType,
) -> Option<(&'static str, u32, Option<u16>)> {
    let audio = match payload_type {
        0 => Some(("PCMU", 8000, None)),
        3 => Some(("GSM", 8000, None)),
        4 => Some(("G723", 8000, None)),
        5 => Some(("DVI4", 8000, None)),
        6 => Some(("DVI4", 16000, None)),
        7 => Some(("LPC", 8000, None)),
        8 => Some(("PCMA", 8000, None)),
        9 => Some(("G722", 8000, None)),
        10 => Some(("L16", 44100, Some(2))),
        11 => Some(("L16", 44100, None)),
        12 => Some(("QCELP", 8000, None)),
        13 => Some(("CN", 8000, None)),
        14 => Some(("MPA", 90000, None)),
        15 => Some(("G728", 8000, None)),
        16 => Some(("DVI4", 11025, None)),
        17 => Some(("DVI4", 22050, None)),
        18 => Some(("G729", 8000, None)),
        _ => None,
    };
    let video = match payload_type {
        25 => Some(("CelB", 90000, None)),
        26 => Some(("JPEG", 90000, None)),
        28 => Some(("nv", 90000, None)),
        31 => Some(("H261", 90000, None)),
        32 => Some(("MPV", 90000, None)),
        33 => Some(("MP2T", 90000, None)),
        34 => Some(("H263", 90000, None)),
        _ => None,
    };
    match media {
        "audio" => audio,
        "video" => video,
        _ => None,
    }
}

/// RFC 3551 section 3 with Tables 4 and 5: every static payload type is read without an
