impl RTCPeerConnection {
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn add_transceiver_sdp(
        mut d: SessionDescription,
        dtls_fingerprints: &[RTCDtlsFingerprint],
        media_engine: &MediaEngine,
        transceivers: &mut [RTCRtpTransceiverInternal],
        ice_params: &RTCIceParameters,
        candidates: &[RTCIceCandidate],
        media_section: &MediaSection,
        params: AddTransceiverSdpParams,
    ) -> Result<(SessionDescription, bool)> {
        let (
            should_add_candidates,
            mid_value,
            dtls_role,
            ice_gathering_state,
            ignore_rid_pause_for_recv,
            write_ssrc_attributes_for_simulcast,
            is_offer,
        ) = (
            params.should_add_candidates,
            params.mid_value,
            params.dtls_role,
            params.ice_gathering_state,
            params.ignore_rid_pause_for_recv,
            params.write_ssrc_attributes_for_simulcast,
            params.is_offer,
        );

        let transceiver = &mut transceivers[media_section.transceiver_index];
        let mut media =
            MediaDescription::new_jsep_media_description(transceiver.kind().to_string(), vec![])
                .with_value_attribute(ATTR_KEY_CONNECTION_SETUP.to_owned(), dtls_role.to_string())
                .with_value_attribute(ATTR_KEY_MID.to_owned(), mid_value.clone())
                .with_ice_credentials(
                    ice_params.username_fragment.clone(),
                    ice_params.password.clone(),
                )
                .with_property_attribute(ATTR_KEY_RTCPMUX.to_owned());
        // Under the mux policy "require" a new m= section of an offer says this endpoint only
        // multiplexes (RFC 9429 sections 4.1.1 and 5.2.1, RFC 8858 section 4.2); a section
        // negotiated before does not get the line (RFC 9429 section 5.2.2: "The
        // 'a=rtcp-mux-only' line MUST NOT be added"), unless the application asked for RFC
        // 8858 section 4.5's form ("the offerer SHOULD associate an SDP 'rtcp-mux-only' with
        // the corresponding SDP media description"). An answer does not carry it (RFC 8858
        // section 4.3), but for the answerer-tagged section of a BUNDLE group whose offer had
        // it (RFC 9143 section 9.3.1.2), which `populate_sdp` adds.
        if is_offer
            && params.rtcp_mux_only
            && (!media_section.renegotiated || params.rtcp_mux_only_renegotiated)
        {
            media = media.with_property_attribute(ATTR_KEY_RTCP_MUX_ONLY.to_owned());
        }
        // RFC 9429 section 5.2.1: an offer's new section has "An "a=rtcp" line ... containing
        // the default value "9 IN IP4 0.0.0.0"" (the default candidate's once there is one);
        // section 5.2.2: "The "a=rtcp" line MUST NOT be added if the most recent answer
        // included an "a=rtcp-mux" line", which this endpoint's answers always do. An answer
        // to an offer with `a=rtcp-mux` has none either (section 5.3.1).
        if is_offer && !media_section.renegotiated {
            media =
                media.with_value_attribute(ATTR_KEY_RTCP.to_owned(), "9 IN IP4 0.0.0.0".to_owned());
        }
        // Reduced-size RTCP (RFC 5506 section 5).
        if media_section.offered_rtcp_rsize.unwrap_or(true) {
            media = media.with_property_attribute(ATTR_KEY_RTCPRSIZE.to_owned());
        }
        // draft-ietf-avtcore-rtp-sframe-03 section 6 / webrtc-encoded-transform 2.1: the
        // transceiver's media is SFrame-encrypted.
        if transceiver.describe_sframe(is_offer) {
            media = media.with_property_attribute(ATTR_KEY_SFRAME.to_owned());
        }

        // RFC 9429 section 5.2.2: a later offer lists every available format, not only the
        // negotiated ones.
        let codecs = if is_offer {
            transceiver.get_offer_codecs(media_engine)
        } else {
            transceiver.get_codecs(media_engine)
        };
        // `SettingEngineBuilder::with_answer_offered_formats_only`: the answer lists the
        // offered formats only (RFC 9429 section 5.3.1 "MAY include formats that are locally
        // supported but not present in the offer"; libwebrtc's form), also when codec
        // preferences name a format the offer lacks.
        let codecs = match &media_section.offered_codecs {
            Some(offered) if !is_offer && params.answer_offered_formats_only => {
                offered_formats_only(codecs, offered)
            }
            _ => codecs,
        };
        // Which repair flows the section has a format for: a sender's RTX / FlexFEC SSRCs are
        // described only then (codec preferences may leave either out). The FEC flow is the
        // FlexFEC coder's: draft-03 (`video/flexfec-03`) or RFC 8627 (`video/flexfec`), each
        // matched exactly as the sender's `find_fec_format` does.
        let repair_flows = RepairFlows {
            rtx: codecs.iter().any(|c| repair_family(&c.rtp_codec) == "rtx"),
            fec: codecs
                .iter()
                .any(|c| is_fec_mime_type(&c.rtp_codec.mime_type)),
        };
        let mut ccfb = false;
        let mut nack_ecn = false;
        let mut rrtr = false;
        // The `xr-format`s other than `rcvr-rtt` the section's formats have (RFC 3611 section
        // 5.1), in the order met: `ecn-sum` with ECN (RFC 6679 section 6.3).
        let mut xr_formats: Vec<String> = vec![];
        for codec in &codecs {
            let name = codec
                .rtp_codec
                .mime_type
                .trim_start_matches("audio/")
                .trim_start_matches("video/")
                .trim_start_matches("application/")
                .to_owned();
            media = media.with_codec(
                codec.payload_type,
                name,
                codec.rtp_codec.clock_rate,
                codec.rtp_codec.channels,
                // This endpoint's own parameters, not the ones the peer stated for the format.
                media_engine.local_fmtp_line(transceiver.kind(), codec, !is_offer),
            );

            // An answer has only feedback the offer has for the format (RFC 4585 section 4.2).
            let feedbacks = match &media_section.offered_codecs {
                Some(offered) => match codec_parameters_search(
                    &codec.rtp_codec,
                    Some(codec.payload_type),
                    offered,
                ) {
                    (offered, CodecMatch::Exact | CodecMatch::Partial) => {
                        rtcp_feedback_intersection(
                            &codec.rtp_codec.rtcp_feedback,
                            &offered.rtp_codec.rtcp_feedback,
                        )
                    }
                    _ => vec![],
                },
                None => codec.rtp_codec.rtcp_feedback.clone(),
            };
            for feedback in &feedbacks {
                // RFC 8888 section 6: "The payload type used with 'ccfb' feedback MUST be the
                // wildcard type ('*')": written once, below.
                if negotiates_ccfb([(feedback.typ.as_str(), feedback.parameter.as_str())]) {
                    ccfb = true;
                    continue;
                }
                // RFC 6679 section 6.2: the ECN feedback packet (`nack ecn`) applies to the
                // RTP session, so it is written once, for every format, below.
                if feedback.typ == crate::rtp_transceiver::rtp_sender::TYPE_RTCP_FB_NACK
                    && feedback.parameter
                        == crate::rtp_transceiver::rtp_sender::rtcp_parameters::RTCP_FB_NACK_ECN
                {
                    nack_ecn = true;
                    continue;
                }
                // XR formats are `a=rtcp-xr` (below), never `a=rtcp-fb` lines.
                if feedback.typ == RTCP_FB_XR {
                    if !xr_formats.contains(&feedback.parameter) {
                        xr_formats.push(feedback.parameter.clone());
                    }
                    continue;
                }
                // Receiver reference times: `a=rtcp-xr`, below; an `a=rtcp-fb ... rrtr` line
                // only where the offer had one.
                if feedback.typ == interceptor::RTCP_FB_RRTR {
                    rrtr = true;
                    if is_rcvr_rtt(&feedback.parameter) {
                        continue;
                    }
                }
                media = media.with_value_attribute(
                    "rtcp-fb".to_owned(),
                    if feedback.parameter.is_empty() {
                        format!("{} {}", codec.payload_type, feedback.typ)
                    } else {
                        format!(
                            "{} {} {}",
                            codec.payload_type, feedback.typ, feedback.parameter
                        )
                    },
                );
            }
        }
        // RFC 9429 section 5.3.1: without codec preferences, "Any currently available media
        // formats that are not present in the current remote description MUST be added after
        // all existing formats" (RFC 3264 section 6.1 lets an answer list them: the offerer
        // may use them in a later offer). Media formats only: a repair format (RTX, FEC, RED)
        // goes with a primary of the answer, and none of them takes feedback (RFC 4585 section
        // 4.2: the answer adds none). Each keeps its registered payload type unless the
        // section already uses it, then takes a free dynamic one.
        // An SFrame section adds them in its own numbering (draft-ietf-avtcore-rtp-sframe-03
        // section 6). The numbers come from `answer_payload_types`, the same for every section
        // of the answer: a payload type the offer uses for another format is never taken,
        // which in a BUNDLE group would give it two configurations (RFC 9143 section 9.1.1).
        // `SettingEngineBuilder::with_answer_offered_formats_only` leaves them out.
        if !is_offer
            && !params.answer_offered_formats_only
            && !transceiver.has_application_codec_preferences()
            && let Some(offered) = &media_section.offered_codecs
            && !codecs.is_empty()
        {
            let sframe = transceiver.use_sframe() == Some(true);
            let mut used: HashSet<u8> = codecs.iter().map(|c| c.payload_type).collect();
            used.extend(offered.iter().map(|c| c.payload_type));
            let available_formats = if sframe {
                media_engine.codecs_for_section(transceiver.kind(), true)
            } else {
                media_engine
                    .registered_codecs_by_kind(transceiver.kind())
                    .to_vec()
            };
            for available in &available_formats {
                if crate::rtp_transceiver::rtp_sender::rtp_codec::is_repair_codec(
                    &available.rtp_codec,
                ) || is_fec_mime_type(&available.rtp_codec.mime_type)
                    || !matches!(
                        codec_parameters_fuzzy_search(&available.rtp_codec, offered).1,
                        CodecMatch::None
                    )
                {
                    continue;
                }
                let Some(&payload_type) = params.answer_payload_types.get(&(
                    sframe,
                    transceiver.kind(),
                    available.payload_type,
                )) else {
                    continue;
                };
                if used.contains(&payload_type) {
                    continue;
                }
                used.insert(payload_type);
                let name = available
                    .rtp_codec
                    .mime_type
                    .trim_start_matches("audio/")
                    .trim_start_matches("video/")
                    .trim_start_matches("application/")
                    .to_owned();
                media = media.with_codec(
                    payload_type,
                    name,
                    available.rtp_codec.clock_rate,
                    available.rtp_codec.channels,
                    media_engine.local_fmtp_line(transceiver.kind(), available, true),
                );
            }
        }
        if ccfb {
            media = media.with_value_attribute(
                ATTR_KEY_RTCP_FB.to_owned(),
                format!("* {TYPE_RTCP_FB_ACK} {RTCP_FB_ACK_CCFB}"),
            );
        }
        if nack_ecn {
            media = media.with_value_attribute(
                ATTR_KEY_RTCP_FB.to_owned(),
                format!(
                    "* {} {}",
                    crate::rtp_transceiver::rtp_sender::TYPE_RTCP_FB_NACK,
                    crate::rtp_transceiver::rtp_sender::rtcp_parameters::RTCP_FB_NACK_ECN
                ),
            );
        }
        // RFC 3611 section 5: XR use is signalled with `a=rtcp-xr`. An offer asks for
        // receiver reference times when this endpoint takes them (`rcvr-rtt=all`, both ways);
        // an answer to an offer with the attribute states what it takes of it, an empty
        // attribute for nothing (section 5.2: "it SHOULD include an empty 'a=rtcp-xr'
        // attribute"); an answer to an offer without it has none (section 5.1: omitted when
        // XR is not used).
        // The other formats (`ecn-sum`, RFC 6679 section 7.1: "the "rtcp-xr" attribute with
        // the "ecn-sum" parameter MUST also be used") follow in the same attribute: an
        // answer's feedback is already what the offer had of them.
        let with_xr_formats = |first: Option<String>| -> Option<String> {
            let formats: Vec<String> = first.into_iter().chain(xr_formats.clone()).collect();
            (!formats.is_empty()).then(|| formats.join(" "))
        };
        let rtcp_xr = match &media_section.offered_rtcp_xr {
            None if is_offer => with_xr_formats(rrtr.then(|| format!("{XR_FORMAT_RCVR_RTT}=all"))),
            None => None,
            Some(offered) => Some(
                with_xr_formats(rrtr.then(|| {
                    offered
                        .iter()
                        .find(|f| is_rcvr_rtt(f))
                        .cloned()
                        .unwrap_or_else(|| format!("{XR_FORMAT_RCVR_RTT}=all"))
                }))
                .unwrap_or_default(),
            ),
        };
        if let Some(rtcp_xr) = rtcp_xr {
            media = media.with_value_attribute(ATTR_KEY_RTCP_XR.to_owned(), rtcp_xr);
        }
        // RFC 6679 section 6.1.1 (RFC 8888 section 7): ECN for RTP. An offer states it in
        // every RTP section (the attribute is IDENTICAL across a BUNDLE group, RFC 8859 section
        // 7.4), an answer only where the offer had a method this endpoint implements. Section
        // 6.1.3: only with a profile that has timely feedback (AVPF) and never over TCP.
        if let Some(preferred) = params.ecn {
            let feedback_profile = media_section.offered_protos.as_ref().is_none_or(|protos| {
                protos
                    .first()
                    .is_some_and(|p| !p.eq_ignore_ascii_case("TCP"))
                    && protos
                        .iter()
                        .any(|p| p.eq_ignore_ascii_case("AVPF") || p.eq_ignore_ascii_case("SAVPF"))
            });
            let value = if !feedback_profile {
                None
            } else if is_offer {
                Some(ecn::offer_value(preferred))
            } else {
                media_section
                    .offered_ecn
                    .as_ref()
                    .and_then(ecn::answer_value)
            };
            if let Some(value) = value {
                media = media.with_value_attribute(ecn::ATTR_KEY_ECN_CAPABLE_RTP.to_owned(), value);
            }
        }
        // RFC 8866 sections 6.4, 6.5 (RFC 7587 section 7 for Opus): the packet times this
        // endpoint wants to receive.
        if transceiver.kind() == RtpCodecKind::Audio && !codecs.is_empty() {
            let packet_time = media_engine.audio_packet_time;
            if let Some(ptime) = packet_time.ptime {
                media = media.with_value_attribute(ATTR_KEY_PTIME.to_owned(), ptime.to_string());
            }
            if let Some(maxptime) = packet_time.maxptime {
                media =
                    media.with_value_attribute(ATTR_KEY_MAXPTIME.to_owned(), maxptime.to_string());
            }
        }
        // RFC 9429 section 5.3.1: "the media formats in the answer MUST include at least one
        // format that is present in the offer ... If no common format exists, the "m=" section
        // is rejected". The transceiver's list falls back to every registered format when the
        // offer matched none of them, so an answer checks it against the offer.
        let no_common_format = !is_offer
            && media_section
                .offered_codecs
                .as_ref()
                .is_some_and(|offered| {
                    !codecs.iter().any(|codec| {
                        !matches!(
                            codec_parameters_fuzzy_search(&codec.rtp_codec, offered).1,
                            CodecMatch::None
                        )
                    })
                });
        if codecs.is_empty() || no_common_format {
            // If we are sender and have no codecs throw an error early
            if !no_common_format && transceiver.describes_sender() {
                return Err(Error::ErrSenderWithNoCodecs);
            }

            // Explicitly reject track if we don't have the codec
            // RFC 9429 Section 5.3.1: Set port=0 to reject, further processing can be skipped
            // However, mid attribute is still needed for offer/answer correlation with BUNDLE
            d = d.with_media(
                MediaDescription {
                    media_name: MediaName {
                        media: transceiver.kind().to_string(),
                        port: RangedPort {
                            value: 0,
                            range: None,
                        },
                        protos: vec![
                            "UDP".to_owned(),
                            "TLS".to_owned(),
                            "RTP".to_owned(),
                            "SAVPF".to_owned(),
                        ],
                        formats: vec!["0".to_owned()],
                    },
                    media_title: None,
                    // We need to include connection information even if we're rejecting a track, otherwise Firefox will fail to
                    // parse the SDP with an error like:
                    // SIPCC Failed to parse SDP: SDP Parse Error on line 50:  c= connection line not specified for every media level, validation failed.
                    // In addition this makes our SDP compliant with RFC 4566 Section 5.7: https://datatracker.ietf.org/doc/html/rfc4566#section-5.7
                    connection_information: vec![ConnectionInformation {
                        network_type: "IN".to_owned(),
                        address_type: "IP4".to_owned(),
                        address: Some(Address {
                            address: "0.0.0.0".to_owned(),
                            ttl: None,
                            range: None,
                        }),
                    }],
                    bandwidth: vec![],
                    encryption_key: None,
                    attributes: vec![],
                }
                .with_value_attribute(ATTR_KEY_MID.to_owned(), mid_value),
            );
            return Ok((d, false));
        }

        let parameters =
            media_engine.get_rtp_parameters_by_kind(transceiver.kind(), transceiver.direction());
        let to_negotiate = transceiver.header_extensions_to_negotiate();
        let to_negotiate = to_negotiate.as_deref();
        // (id, URI, encrypted form): one form per URI in an answer, both in an offer that
        // offers best-effort encryption (RFC 6904 section 4.1).
        let mut written: Vec<(u16, String, bool)> = vec![];
        for rtp_extension in &parameters.header_extensions {
            if let Some(uris) = to_negotiate
                && !uris.contains(&rtp_extension.uri)
            {
                continue;
            }
            let (id, encrypted) = if media_section.match_extensions.is_empty() {
                (rtp_extension.id, rtp_extension.encrypted)
            } else if let Some(offered) = media_section.match_extensions.get(&rtp_extension.uri) {
                (offered.id, offered.encrypted)
            } else {
                continue;
            };
            if written.iter().any(|(i, u, e)| {
                *i == id || (u == &rtp_extension.uri && (*e == encrypted || !is_offer))
            }) {
                continue;
            }
            written.push((id, rtp_extension.uri.clone(), encrypted));
        }
        if is_offer && let Some(uris) = to_negotiate {
            let taken: Vec<(u16, String)> =
                written.iter().map(|(i, u, _)| (*i, u.clone())).collect();
            for (id, uri, encrypted) in reoffered_header_extensions(
                media_engine,
                transceiver.kind(),
                transceiver.direction(),
                uris,
                &taken,
            ) {
                written.push((id, uri, encrypted));
            }
        }
        // RFC 6464 section 4: "the semantics chosen for a header extension element (including
        // its vad setting) for a particular extension identifier value MUST NOT be changed
        // within an RTP session". The extension attributes an id was negotiated with go with it:
        // an answer repeats the offer's, a later offer the ones the remote description gave it.
        let extension_attributes = |id: u16, uri: &str| -> Option<String> {
            // The mapping the remote description gave the id: the offer an answer answers, or
            // for a later offer the current remote description.
            media_section
                .match_extensions
                .get(uri)
                .filter(|matched| matched.id == id)
                .and_then(|matched| matched.attributes.clone())
                .filter(|attributes| !attributes.is_empty())
        };
        let ext_attr_of = |id: u16, uri: &str, encrypted: bool| -> Option<String> {
            let attributes = extension_attributes(id, uri);
            match (encrypted, attributes) {
                (true, Some(attributes)) => Some(format!("{uri} {attributes}")),
                (true, None) => Some(uri.to_owned()),
                (false, attributes) => attributes,
            }
        };
        for (id, uri, encrypted) in &written {
            // RFC 8285 section 7: an extension may be restricted to a direction. An offer
            // states the one the extension was registered for when the section sends and
            // receives (RFC 6465 section 5: a client that does not mix "would hence have to
            // always include the direction parameter ... with a value of 'recvonly'"); an
            // answer reverses what the offer restricted, within what was registered, and
            // leaves out an extension it can use in neither direction.
            // webrtc-extensions 4.1: the direction `[[HeaderExtensionsToNegotiate]]` gives
            // the extension, when the application set the list or an answer did.
            let registered = transceiver.header_extension_direction(uri).or_else(|| {
                media_engine
                    .header_extensions
                    .iter()
                    .find(|e| e.uri == *uri)
                    .and_then(|e| e.allowed_direction)
            });
            if registered == Some(RTCRtpTransceiverDirection::Inactive) {
                // Offered inactive; in an answer, only as the offer allowed.
                if is_offer || media_section.match_extensions.contains_key(uri) {
                    let ext_uri = Url::parse(if *encrypted { ENCRYPT_URI } else { uri })?;
                    let ext_attr = ext_attr_of(*id, uri, *encrypted);
                    media = media.with_extmap(sdp::extmap::ExtMap {
                        value: *id,
                        uri: Some(ext_uri),
                        direction: sdp::direction::Direction::Inactive,
                        ext_attr,
                    });
                }
                continue;
            }
            let Some(direction) = extension_direction(
                registered,
                media_section.match_extension_directions.get(uri).cloned(),
                media_section
                    .answer_direction
                    .unwrap_or_else(|| transceiver.direction()),
            ) else {
                continue;
            };
            let ext_uri = Url::parse(if *encrypted { ENCRYPT_URI } else { uri })?;
            let ext_attr = ext_attr_of(*id, uri, *encrypted);
            media = media.with_extmap(sdp::extmap::ExtMap {
                value: *id,
                uri: Some(ext_uri),
                direction,
                ext_attr,
            });
        }
        // RFC 6904 section 4.1: the clear form of an extension answered encrypted is
        // answered "inactive".
        for (id, uri) in &media_section.superseded_extensions {
            if written.iter().any(|(_, u, e)| u == uri && *e) {
                media = media.with_extmap(sdp::extmap::ExtMap {
                    value: *id,
                    uri: Some(Url::parse(uri)?),
                    direction: sdp::direction::Direction::Inactive,
                    ext_attr: None,
                });
            }
        }

        // The section's direction: an answer's is the transceiver's [[Direction]] intersected
        // with the reverse of the offered one (RFC 9429 section 5.3.1, RFC 3264 section 6.1);
        // an offer states [[Direction]] itself.
        let mut direction = media_section
            .answer_direction
            .unwrap_or_else(|| transceiver.direction());

        // RFC 9429 section 3.6.1 (and 5.2.1, 5.3.1): a receiving video section states the
        // frame sizes this endpoint can receive; when its limits permit none, the attribute
        // is left out and the section does not receive.
        let mut imageattrs = vec![];
        if transceiver.kind() == RtpCodecKind::Video && direction.has_recv() {
            let formats: Vec<(u8, String)> = codecs
                .iter()
                .filter(|codec| {
                    repair_family(&codec.rtp_codec).is_empty()
                        && !is_fec_mime_type(&codec.rtp_codec.mime_type)
                })
                .map(|codec| (codec.payload_type, codec.rtp_codec.mime_type.clone()))
                .collect();
            match imageattr::imageattr_lines(
                &formats,
                params.video_receive_limits,
                &params.codec_video_receive_limits,
            ) {
                Some(lines) => imageattrs = lines,
                None => {
                    direction = if direction.has_send() {
                        RTCRtpTransceiverDirection::Sendonly
                    } else {
                        RTCRtpTransceiverDirection::Inactive
                    }
                }
            }
        }
        for line in imageattrs {
            media = media.with_value_attribute(ATTR_KEY_IMAGEATTR.to_owned(), line);
        }

        // What this endpoint would like to receive (RFC 3264 sections 5 and 6:
        // `RTCRtpTransceiver::set_receive_bandwidth`), in a section that receives.
        if let Some(tias) = transceiver.receive_bandwidth()
            && direction.has_recv()
        {
            media.bandwidth.extend(receive_bandwidth_lines(tias));
        }

        // `a=rid` and `a=simulcast` (RFC 8851, RFC 8853).
        let formats: HashSet<u8> = codecs.iter().map(|codec| codec.payload_type).collect();
        // RFC 8851 section 6.3 step 4: a `pt=` keeps the formats this description has, and a
        // line that would keep none is discarded. `None`: the line is discarded.
        let kept_formats = |rid: &SimulcastRid| -> Option<Vec<u8>> {
            let kept: Vec<u8> = rid
                .formats
                .iter()
                .copied()
                .filter(|pt| formats.contains(pt))
                .collect();
            (rid.formats.is_empty() || !kept.is_empty()).then_some(kept)
        };
        // RFC 8853 section 5.2: `~` marks a stream initially paused, which "MUST" go with
        // RFC 7728 pause/resume negotiated for the section: the section's formats carry
        // `ccm pause` (offered, or negotiated in an answer), or the setting writes it anyway.
        let pauses = codecs.iter().any(|codec| {
            codec.rtp_codec.rtcp_feedback.iter().any(|feedback| {
                feedback.typ == crate::rtp_transceiver::rtp_sender::TYPE_RTCP_FB_CCM
                    && interceptor::PauseCapability::parse(&feedback.parameter).is_some()
            })
        });
        let sc_id = |id: &str, paused: bool| -> String {
            if paused && (params.rid_pause_marks || pauses) {
                format!("~{id}")
            } else {
                id.to_owned()
            }
        };
        let mut recv_sc_list: Vec<String> = vec![];
        let mut send_sc_list: Vec<String> = vec![];
        // The streams the remote side sends: each of its `send` rids is answered `recv` with
        // its restrictions kept (RFC 8851 section 6.3), and mirrored in a later offer.
        if direction.has_recv() {
            for rid in media_section
                .rid_map
                .iter()
                .filter(|rid| rid.direction == SimulcastDirection::Send)
            {
                let Some(pts) = kept_formats(rid) else {
                    continue;
                };
                let line = if !is_offer && params.w3c_simulcast_answer {
                    rid.bare_line(SimulcastDirection::Recv)
                } else {
                    rid.line(SimulcastDirection::Recv, pts)
                };
                media = media.with_value_attribute(SDP_ATTRIBUTE_RID.to_owned(), line);
                if rid.simulcast {
                    recv_sc_list.push(sc_id(&rid.id, rid.paused));
                }
            }
        }
        // An offer that asks to receive simulcast (RFC 8853 section 5.3.1): the streams the
        // application named, unless the remote side's send streams are mirrored above.
        if is_offer
            && direction.has_recv()
            && recv_sc_list.is_empty()
            && transceiver.receive_simulcast().len() > 1
        {
            for rid in transceiver.receive_simulcast() {
                media =
                    media.with_value_attribute(SDP_ATTRIBUTE_RID.to_owned(), format!("{rid} recv"));
                recv_sc_list.push(rid.clone());
            }
        }
        // The streams this endpoint sends: one `a=rid ... send` per encoding of a sender with
        // several encodings (RFC 9429 section 5.2.1). An answer has only the ones the offer
        // asked to receive (RFC 8853 section 5.3.2: "The answerer MUST NOT add any simulcast
        // streams"), with the offered restrictions (RFC 8851 section 6.3); an offer has each
        // encoding, with the restrictions the application gave it.
        if direction.has_send()
            && let Some(sender) = transceiver.sender()
        {
            // An offer also lists the streams remote answers rejected, should the sender keep
            // them for it (`with_rejected_rids_kept_in_offers`, RFC 9429 section 5.2.2: the
            // a=rid and a=simulcast lines "MUST stay the same").
            let encodings: Vec<(_, bool)> = if is_offer {
                sender.offered_encodings()
            } else {
                sender
                    .send_encodings()
                    .iter()
                    .map(|encoding| (encoding, false))
                    .collect()
            };
            let is_simulcast = encodings.len() > 1
                && encodings
                    .iter()
                    .all(|(encoding, _)| !encoding.rtp_coding_parameters.rid.is_empty());
            if is_simulcast {
                let mut lines = 0;
                for (encoding, rejected) in encodings {
                    let coding = &encoding.rtp_coding_parameters;
                    let (rid, listed) = if is_offer {
                        (
                            // What the offer that negotiated the stream said, should an
                            // answer have tightened it (RFC 9429 section 5.2.2).
                            SimulcastRid::from_restrictions(
                                &coding.rid,
                                SimulcastDirection::Send,
                                sender
                                    .offered_rid_restrictions(&coding.rid)
                                    .unwrap_or(&coding.rid_restrictions),
                            ),
                            true,
                        )
                    } else {
                        let Some(offered) = media_section.rid_map.iter().find(|rid| {
                            rid.direction == SimulcastDirection::Recv && rid.id == coding.rid
                        }) else {
                            continue;
                        };
                        (offered.clone(), offered.simulcast)
                    };
                    let Some(pts) = kept_formats(&rid) else {
                        continue;
                    };
                    let line = if !is_offer && params.w3c_simulcast_answer {
                        rid.bare_line(SimulcastDirection::Send)
                    } else {
                        rid.line(SimulcastDirection::Send, pts)
                    };
                    media = media.with_value_attribute(SDP_ATTRIBUTE_RID.to_owned(), line);
                    lines += 1;
                    if listed {
                        // A rejected stream is not sent: paused, in RFC 8853 section 5.3.4's
                        // "current pause state".
                        let paused = !encoding.active
                            || rejected
                            || (!is_offer && rid.paused && !ignore_rid_pause_for_recv);
                        send_sc_list.push(sc_id(&coding.rid, paused));
                    }
                }
                // RFC 9429 section 5.2.1: an `a=simulcast` line when "more than one 'a=rid'
                // line has been generated".
                if is_offer && lines < 2 {
                    send_sc_list.clear();
                }
            }
        }

        media = RTCPeerConnection::add_sender_sdp(
            media,
            media_engine,
            transceiver,
            write_ssrc_attributes_for_simulcast,
            repair_flows,
            params.msid_appdata,
        )?;
        // RFC 8853 section 5.1: one line, each direction at most once.
        let mut sc_attr = vec![];
        if !recv_sc_list.is_empty() {
            sc_attr.push(format!("recv {}", recv_sc_list.join(";")));
        }
        if !send_sc_list.is_empty() {
            sc_attr.push(format!("send {}", send_sc_list.join(";")));
        }
        if !sc_attr.is_empty() {
            media =
                media.with_value_attribute(SDP_ATTRIBUTE_SIMULCAST.to_owned(), sc_attr.join(" "));
        }

        media = media.with_property_attribute(direction.to_string());

        for fingerprint in dtls_fingerprints {
            media = media.with_fingerprint(
                fingerprint.algorithm.to_owned(),
                fingerprint.value.to_uppercase(),
            );
        }

        if should_add_candidates {
            media = add_candidates_to_media_descriptions(candidates, media, ice_gathering_state)?;
        }

        Ok((d.with_media(media), true))
    }

    /// The sender's `a=msid` lines and source attributes. Its `a=rid` lines are the caller's.
    fn add_sender_sdp(
        mut media: MediaDescription,
        media_engine: &MediaEngine,
        transceiver: &mut RTCRtpTransceiverInternal,
        write_ssrc_attributes_for_simulcast: bool,
        repair_flows: RepairFlows,
        msid_appdata: bool,
    ) -> Result<MediaDescription> {
        let cname = media_engine.rtcp_cname.as_str();
        // Every transceiver has a sender; one that has neither a track nor a sending
        // direction is not described (RFC 9429 section 5.2.1).
        let negotiated_header_extensions = transceiver.negotiated_header_extensions().to_vec();
        let mut transceiver_msid = None;
        if transceiver.describes_sender()
            && let Some(sender) = transceiver.sender_mut()
        {
            let (encodings, track) = (
                sender
                    .get_parameters(media_engine, &negotiated_header_extensions)
                    .encodings
                    .clone(),
                sender.track(),
            );

            let is_simulcast = encodings.len() > 1
                && encodings
                    .iter()
                    .all(|encoding| !encoding.rtp_coding_parameters.rid.is_empty());

            // One `a=msid` line per MediaStream the sender is associated with, "omitting the
            // "appdata" field" (RFC 9429 section 5.2.1; the track id with
            // `with_msid_appdata`); a sender in no stream writes the stream id `-`.
            let track_id = track.track_id().to_string();
            let mut stream_ids: Vec<String> = vec![];
            for stream_id in sender.streams() {
                if !stream_ids.contains(stream_id) {
                    stream_ids.push(stream_id.clone());
                }
            }
            if stream_ids.is_empty() {
                stream_ids.push("-".to_owned());
            }
            // RFC 8830 section 2: `msid-id = 1*64token-char` and `msid-appdata =
            // 1*64token-char`. A stream or track id the application chose that is not one
            // cannot be written: the line would not parse (a space would even make it three
            // tokens), so the description is not made. The track id is checked also without
            // appdata: the source-level `msid` attribute carries it.
            for id in stream_ids.iter().chain(std::iter::once(&track_id)) {
                if !is_msid_token(id) {
                    return Err(Error::SdpInvalidValue(format!(
                        "the id {id:?} cannot be written in a=msid: an msid-id or appdata is 1 \
                         to 64 token characters (RFC 8830 section 2)"
                    )));
                }
            }
            // The source-level `msid` (RFC 8830 appendix A) names the same first stream.
            let source_stream = stream_ids[0].clone();
            let msid: Vec<String> = stream_ids
                .into_iter()
                .map(|stream_id| {
                    if msid_appdata {
                        format!("msid:{stream_id} {track_id}")
                    } else {
                        format!("msid:{stream_id}")
                    }
                })
                .collect();
            for line in &msid {
                media = media.with_property_attribute(line.clone());
            }
            transceiver_msid = Some(msid);

            if write_ssrc_attributes_for_simulcast || !is_simulcast {
                for encoding in &encodings {
                    if let Some(&ssrc) = encoding.rtp_coding_parameters.ssrc.as_ref() {
                        let rtx_flow = encoding
                            .rtp_coding_parameters
                            .rtx
                            .as_ref()
                            .filter(|_| repair_flows.rtx);
                        let fec_flow = encoding
                            .rtp_coding_parameters
                            .fec
                            .as_ref()
                            .filter(|_| repair_flows.fec);
                        if let Some(rtx) = rtx_flow {
                            media = media.with_value_attribute(
                                ATTR_KEY_SSRC_GROUP.to_owned(),
                                format!(
                                    "{} {} {}",
                                    SEMANTIC_TOKEN_FLOW_IDENTIFICATION, ssrc, rtx.ssrc
                                ),
                            );
                        }

                        if let Some(fec) = fec_flow {
                            // `FEC-FR` (RFC 5956), not the older `FEC` semantic of RFC 4756:
                            // FlexFEC repair flows are grouped under the FEC framework, and
                            // `parse_media_section` below only recognises `FEC-FR`, so writing
                            // `FEC` here produced an offer this crate could not parse back.
                            media = media.with_value_attribute(
                                ATTR_KEY_SSRC_GROUP.to_owned(),
                                format!(
                                    "{} {} {}",
                                    SEMANTIC_TOKEN_FORWARD_ERROR_CORRECTION_FRAMEWORK,
                                    ssrc,
                                    fec.ssrc
                                ),
                            );
                        }

                        let mut sources = vec![ssrc];
                        sources.extend(rtx_flow.map(|rtx| rtx.ssrc));
                        sources.extend(fec_flow.map(|fec| fec.ssrc));
                        for source in sources {
                            media =
                                with_source_attributes(media, source, &source_stream, track, cname);
                            // RFC 5576 sections 5 and 6.2: a source that moved after a
                            // collision names the SSRCs it had, once.
                            let previous = sender.previous_ssrcs(source);
                            if !previous.is_empty() {
                                let previous: Vec<String> =
                                    previous.iter().map(|ssrc| ssrc.to_string()).collect();
                                media = media.with_value_attribute(
                                    ATTR_KEY_SSRC.to_owned(),
                                    format!("{source} previous-ssrc:{}", previous.join(" ")),
                                );
                            }
                        }
                    }
                }
            }
        }
        // RFC 9429 sections 5.2.2 and 5.3.2: "the 'a=msid' lines MUST stay the same" for a
        // transceiver that is not stopped, "regardless of changes to the transceiver's
        // direction or track": one that no longer has a track or a sending direction keeps
        // the lines its section had.
        match transceiver_msid {
            Some(msid) => transceiver.set_described_msid(msid),
            None if !transceiver.stopped() => {
                for line in transceiver.described_msid() {
                    media = media.with_property_attribute(line.clone());
                }
            }
            None => {}
        }

        Ok(media)
    }
}

/// The source attributes of one of a sender's SSRCs (RFC 5576 section 4.1): `cname` (section
/// 6.1: "the same as the CNAME that the source uses in RTCP", so the connection's one CNAME,
/// RFC 7022, whatever the track) and `msid` (RFC 8830 appendix A, registered as a source
/// attribute). The Plan B
/// `mslabel` and `label` attributes are not written: RFC 5576 section 4.1 has source
/// attributes registered with IANA, and neither is.
fn with_source_attributes(
    media: MediaDescription,
    ssrc: SSRC,
    stream_id: &str,
    track: &MediaStreamTrack,
    cname: &str,
) -> MediaDescription {
    media
        .with_value_attribute(ATTR_KEY_SSRC.to_owned(), format!("{ssrc} cname:{cname}"))
        .with_value_attribute(
            ATTR_KEY_SSRC.to_owned(),
            format!("{ssrc} msid:{stream_id} {}", track.track_id()),
        )
}

/// Whether an m-section has a format for a sender's RTX (RFC 4588) and FlexFEC
/// (draft-ietf-payload-flexible-fec-scheme-03 `video/flexfec-03`, or RFC 8627 `video/flexfec`)
/// flows.
#[derive(Debug, Copy, Clone)]
pub(crate) struct RepairFlows {
    pub(crate) rtx: bool,
    pub(crate) fec: bool,
}

/// Rejects a section of an answer that was written in full: port zero, and no `a=candidate`
/// lines (RFC 8839 section 4.2.1.6: with the port set to zero "the agent SHOULD NOT include
/// ICE-related SDP "candidate" attributes in that "m=" section"), nor `a=end-of-candidates`.
/// Whether it took candidates out: the next section written takes them then.
fn reject_written_section(media: &mut MediaDescription) -> bool {
    media.media_name.port = RangedPort {
        value: 0,
        range: None,
    };
    let before = media.attributes.len();
    media
        .attributes
        .retain(|a| a.key != "candidate" && a.key != "end-of-candidates");
    media.attributes.len() != before
}

/// Makes a section of an initial offer bundle-only (RFC 9143 sections 6 and 7.2.1): port
/// zero, `a=bundle-only`, and none of the BUNDLE attributes (the IDENTICAL and TRANSPORT
/// categories of RFC 8859), which "the offerer MUST NOT include ... in bundle-only 'm='
/// sections" (RFC 9143 section 7.1.3): they are the offerer-tagged section's.
///
/// With `rtcp_mux` (`SettingEngineBuilder::with_bundle_only_sections_in_browser_form`)
/// an RTP section keeps one BUNDLE attribute, `a=rtcp-mux`, against RFC 9143 sections 7.1.3 and
/// 9.3.1.1: Chromium, WebKit and Firefox refuse an offer whose bundle-only RTP section lacks it.
fn make_bundle_only(media: &mut MediaDescription, rtcp_mux: bool) {
    media.media_name.port = RangedPort {
        value: 0,
        range: None,
    };
    media
        .attributes
        .retain(|a| !BUNDLE_ATTRIBUTES.contains(&a.key.as_str()) && a.key != "end-of-candidates");
    if rtcp_mux && media.media_name.media != MEDIA_SECTION_APPLICATION {
        media
            .attributes
            .push(sdp::description::common::Attribute::new(
                ATTR_KEY_RTCPMUX.to_owned(),
                None,
            ));
    }
    media
        .attributes
        .push(sdp::description::common::Attribute::new(
            ATTR_KEY_BUNDLE_ONLY.to_owned(),
            None,
        ));
}

/// Whether a BUNDLE attribute (`a=rtcp-mux`, `a=rtcp-rsize`: RFC 8859 category IDENTICAL)
/// applies to `media`: the section has it, or the tagged section of its BUNDLE group has it.
/// RFC 9143 section 7.1.3: in an initial offer a bundle-only section leaves the BUNDLE
/// attributes to the offerer-tagged section, and in a subsequent offer or an answer they are
/// "only in the tagged 'm=' section" and "will apply to each bundled 'm=' section".
pub(crate) fn has_bundle_attribute(
    desc: &SessionDescription,
    media: &MediaDescription,
    key: &str,
) -> bool {
    media.has_attribute(key) || tagged_section(desc, media).is_some_and(|m| m.has_attribute(key))
}

/// Whether an RTP section of a remote description multiplexes RTP and RTCP. A section says so
/// itself with `a=rtcp-mux`. In an initial offer every bundled RTP section does, the
/// bundle-only ones excepted (RFC 9143 section 9.3.1.1: "the offerer MUST include an SDP
/// 'rtcp-mux' attribute in each bundled 'm=' section (excluding any bundle-only 'm='
/// sections)"), so only a bundle-only section takes the attribute from the offerer-tagged
/// one there. In a subsequent offer or an answer the attribute is in the tagged section only
/// (section 7.1.3) and applies to every bundled section.
pub(crate) fn section_multiplexes_rtcp(
    desc: &SessionDescription,
    media: &MediaDescription,
    initial_offer: bool,
) -> bool {
    if has_rtcp_mux(media) {
        return true;
    }
    if initial_offer && !media.has_attribute(ATTR_KEY_BUNDLE_ONLY) {
        return false;
    }
    has_bundle_attribute(desc, media, ATTR_KEY_RTCPMUX)
}

/// The tagged section of the BUNDLE group `media` is in: the first tag of the group that is
/// neither rejected nor bundle-only (RFC 9143 sections 7.2 and 7.3.1).
pub(crate) fn tagged_section<'a>(
    desc: &'a SessionDescription,
    media: &MediaDescription,
) -> Option<&'a MediaDescription> {
    let mid = get_mid_value(media);
    bundle_groups(desc)
        .into_iter()
        .find(|group| mid.is_some_and(|mid| group.contains(&mid.as_str())))
        .and_then(|group| {
            group.into_iter().find_map(|tag| {
                desc.media_descriptions.iter().find(|candidate| {
                    get_mid_value(candidate).is_some_and(|mid| mid == tag)
                        && !candidate.has_attribute(ATTR_KEY_BUNDLE_ONLY)
                        && !is_rejected_media(candidate)
                })
            })
        })
}

