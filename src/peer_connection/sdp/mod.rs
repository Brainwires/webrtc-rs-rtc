pub(crate) const MEDIA_SECTION_APPLICATION: &str = "application";

/// TrackDetails represents any media source that can be represented in a SDP
/// This isn't keyed by SSRC because it also needs to support rid based sources
#[derive(Default, Debug, Clone)]
pub(crate) struct TrackDetails {
    pub(crate) mid: String,
    pub(crate) kind: RtpCodecKind,
    /// The first MediaStream the track is in (`-` when it is in none), the id its
    /// `MediaStreamTrack` carries.
    pub(crate) stream_id: MediaStreamId,
    /// Every MediaStream the track is in, one per `a=msid` line, without `-` (RFC 8830
    /// section 2: "Multiple media descriptions with the same value for msid-id ... If
    /// multiple media descriptions ... one track in several streams").
    pub(crate) stream_ids: Vec<MediaStreamId>,
    /// The msid-appdata, the sender's track id. Empty when the `a=msid` lines carry none
    /// (the form RFC 9429 section 5.2.1 has senders write): the recipient names the track
    /// itself (RFC 8830 section 3).
    pub(crate) track_id: MediaStreamTrackId,
    pub(crate) ssrc: Option<SSRC>,
    pub(crate) rtx_ssrc: Option<SSRC>,
    pub(crate) fec_ssrc: Option<SSRC>,
    pub(crate) rids: Vec<String>,
    /// What each rid's `a=rid` line restricts the stream to (RFC 8851 section 5).
    pub(crate) rid_restrictions: HashMap<String, RTCRtpRidRestrictions>,
    /// The further simulcast streams of the track an `a=ssrc-group:SIM` names, after the
    /// first one (`ssrc`).
    pub(crate) ssrc_layers: Vec<SsrcLayer>,
    /// With `rids`: the streams the section also declares by SSRC (`a=ssrc`, each `SIM`
    /// member one), with the repair flows `a=ssrc-group:FID` / `FEC-FR` pair them with, in
    /// the order of their `a=ssrc` lines. RFC 9143 section 9.2 associates a packet whose SSRC
    /// the section declares with the section; a packet of one that carries no RID is received
    /// as a stream without a rid.
    pub(crate) declared_ssrcs: Vec<SsrcLayer>,
}

/// The `ssrc-group` semantics of simulcast streams sent as SSRCs of one track, without
/// RFC 8853 rids (registered in RFC 5576's registry by libwebrtc's use; "SIM").
const SEMANTIC_TOKEN_SIMULCAST: &str = "SIM";

/// A stream an m= section declares by SSRC with its repair flows (RFC 5576 section 4.2, RFC
/// 4588 section 8.1): one simulcast stream of an `a=ssrc-group:SIM` track, or a declared
/// stream of a section with `a=rid`.
#[derive(Default, Debug, Clone, PartialEq, Eq)]
pub(crate) struct SsrcLayer {
    pub(crate) ssrc: SSRC,
    pub(crate) rtx_ssrc: Option<SSRC>,
    pub(crate) fec_ssrc: Option<SSRC>,
}

/// What the `a=ssrc-group` lines of a media section say (RFC 5576 section 4.2): a group
/// lists one or more ssrc-ids, and any number of them.
#[derive(Default, Debug)]
struct SsrcGroups {
    /// The RTX flow of each primary: the second id of its `FID` group (RFC 4588 section 8.6).
    rtx: HashMap<SSRC, SSRC>,
    /// The FEC repair flow of each source of a `FEC-FR` group (RFC 5956 section 4.3).
    fec: HashMap<SSRC, SSRC>,
    /// Every SSRC that is a repair flow of another, not a track of its own.
    repair_flows: HashSet<SSRC>,
    /// The members of each `SIM` group, in order.
    simulcast: Vec<Vec<SSRC>>,
}

impl SsrcGroups {
    fn of(media: &MediaDescription) -> Self {
        let mut lists: Vec<(&str, Vec<SSRC>)> = vec![];
        for value in media
            .attributes
            .iter()
            .filter(|a| a.key == ATTR_KEY_SSRC_GROUP)
            .filter_map(|a| a.value.as_deref())
        {
            let mut tokens = value.split(' ');
            let semantics = tokens.next().unwrap_or_default();
            let Ok(ids) = tokens
                .map(str::parse::<SSRC>)
                .collect::<std::result::Result<Vec<_>, _>>()
            else {
                log::warn!("a=ssrc-group:{value}: an ssrc-id is not a number");
                continue;
            };
            if !ids.is_empty() {
                lists.push((semantics, ids));
            }
        }

        let mut groups = SsrcGroups::default();
        // `FID` (RFC 5888 section 8.4, RFC 4588 section 8.6): the first id is the source,
        // every further one a flow of the same source, the first of them its RTX flow.
        let mut primaries: HashSet<SSRC> = HashSet::new();
        for (semantics, ids) in &lists {
            if *semantics == SEMANTIC_TOKEN_FLOW_IDENTIFICATION && ids.len() >= 2 {
                groups.rtx.entry(ids[0]).or_insert(ids[1]);
                groups.repair_flows.extend(&ids[1..]);
                primaries.insert(ids[0]);
            } else if *semantics == SEMANTIC_TOKEN_SIMULCAST {
                primaries.extend(ids);
            }
        }
        // `FEC-FR` (RFC 5956 sections 4.1, 4.3): one or more source flows and the additive
        // repair flows that protect them. The first id is a source (as WebRTC writes it,
        // `FEC-FR <source> <repair>`, RFC 8627 section 6); a further id is a source too when
        // it is a primary of its own (an `FID` source or a `SIM` stream, as `S1 S2 R2` in
        // section 4.2), a repair flow otherwise.
        for (semantics, ids) in &lists {
            if *semantics != SEMANTIC_TOKEN_FORWARD_ERROR_CORRECTION_FRAMEWORK || ids.len() < 2 {
                continue;
            }
            let (mut sources, mut repairs): (Vec<SSRC>, Vec<SSRC>) = (vec![], vec![]);
            for (i, ssrc) in ids.iter().enumerate() {
                if i == 0 || primaries.contains(ssrc) {
                    sources.push(*ssrc);
                } else {
                    repairs.push(*ssrc);
                }
            }
            let Some(&repair) = repairs.first() else {
                continue;
            };
            for source in sources {
                groups.fec.entry(source).or_insert(repair);
            }
            groups.repair_flows.extend(repairs);
        }
        groups.simulcast = lists
            .into_iter()
            .filter(|(semantics, ids)| *semantics == SEMANTIC_TOKEN_SIMULCAST && ids.len() >= 2)
            .map(|(_, ids)| ids)
            .collect();
        for members in &mut groups.simulcast {
            members.retain(|ssrc| !groups.repair_flows.contains(ssrc));
        }
        groups
    }
}

pub(crate) fn track_details_for_ssrc(
    track_details: &[TrackDetails],
    ssrc: SSRC,
) -> Option<&TrackDetails> {
    track_details.iter().find(|x| x.ssrc == Some(ssrc))
}

pub(crate) fn track_details_for_rid<'a>(
    track_details: &'a [TrackDetails],
    mid: &String,
    rid: &String,
) -> Option<&'a TrackDetails> {
    track_details
        .iter()
        .find(|x| &x.mid == mid && x.rids.contains(rid))
}

/// extract all TrackDetails from an SDP.
///
/// Rid-ids are read with `rid_ids` (`SettingEngine::rid_id_grammar`).
pub(crate) fn track_details_from_sdp(
    s: &SessionDescription,
    rid_ids: RidIdGrammar,
) -> Vec<TrackDetails> {
    let mut incoming_tracks = vec![];

    for media in &s.media_descriptions {
        // Tracks in the order their `a=ssrc` lines first appear. A track a later
        // `a=ssrc-group` names as a repair flow is removed by clearing its slot, and
        // `slot_by_ssrc` finds a track by SSRC (unique within the section) without a scan.
        let mut track_slots: Vec<Option<TrackDetails>> = vec![];
        let mut slot_by_ssrc: HashMap<SSRC, usize> = HashMap::new();

        // The section's `a=msid` lines (RFC 8830 section 2), read before anything else: they
        // name the track's streams whatever a legacy `a=ssrc:<n> msid:` attribute says.
        let msid = media_msid(media);
        let has_media_msid = msid.is_some();
        let (stream_ids, msid_track_id) = msid.unwrap_or_default();
        let mut stream_id = if has_media_msid {
            stream_ids.first().map_or("-", String::as_str)
        } else {
            ""
        };
        let mut track_id = msid_track_id.as_str();

        // If media section is recvonly or inactive skip
        if media.attribute(ATTR_KEY_RECV_ONLY).is_some()
            || media.attribute(ATTR_KEY_INACTIVE).is_some()
        {
            continue;
        }

        let mid_value = match get_mid_value(media) {
            Some(mid_value) if !mid_value.is_empty() => mid_value,
            _ => continue,
        };

        if media.is_webrtc_datachannel() {
            continue;
        }

        let codec_type = RtpCodecKind::from(media.media_name.media.as_str());
        if codec_type == RtpCodecKind::Unspecified || is_unknown_media_protocol(media) {
            continue;
        }

        // RFC 5576 section 4.2: a group "MUST list at least one <ssrc-id> for a group and MAY
        // list any number of additional ones". Read before the `a=ssrc` lines, wherever the
        // groups stand in the section.
        let groups = SsrcGroups::of(media);

        for attr in &media.attributes {
            match attr.key.as_str() {
                // Handle `a=msid:<stream_id> <track_label>` The first value is the same as MediaStream.id
                // in the browser and can be used to figure out which tracks belong to the same stream. The browser should
                // figure this out automatically when an ontrack event is emitted on RTCPeerConnection.
                // `a=msid` lines were read by `media_msid` above.
                ATTR_KEY_MSID => {}

                ATTR_KEY_SSRC => {
                    if let Some(value) = &attr.value {
                        let split: Vec<&str> = value.split(' ').collect();
                        let ssrc = match split[0].parse::<u32>() {
                            Ok(ssrc) => ssrc,
                            Err(err) => {
                                log::warn!("Failed to parse SSRC: {err}");
                                continue;
                            }
                        };

                        if groups.repair_flows.contains(&ssrc) {
                            continue; // A repair flow (RTX, FEC) of a primary, not a track.
                        }

                        // The source-level msid of a description without `a=msid` lines
                        // (the form that predates them).
                        if !has_media_msid && split.len() == 3 && split[1].starts_with("msid:") {
                            stream_id = &split[1]["msid:".len()..];
                            track_id = split[2];
                        }

                        if let Some(track) = slot_by_ssrc
                            .get(&ssrc)
                            .and_then(|&slot| track_slots[slot].as_mut())
                        {
                            track.mid = mid_value.to_string();
                            track.kind = codec_type;
                            stream_id.clone_into(&mut track.stream_id);
                            track_id.clone_into(&mut track.track_id);
                            track.ssrc = Some(ssrc);
                        } else {
                            let track_details = TrackDetails {
                                mid: mid_value.to_string(),
                                kind: codec_type,
                                stream_id: stream_id.to_owned(),
                                track_id: track_id.to_owned(),
                                ssrc: Some(ssrc),
                                ..Default::default()
                            };
                            slot_by_ssrc.insert(ssrc, track_slots.len());
                            track_slots.push(Some(track_details));
                        }
                    }
                }
                _ => {}
            };
        }

        for track in track_slots.iter_mut().flatten() {
            if let Some(ssrc) = track.ssrc {
                track.rtx_ssrc = groups.rtx.get(&ssrc).copied();
                track.fec_ssrc = groups.fec.get(&ssrc).copied();
            }
        }

        // RFC 5576 section 4.2 with the `SIM` semantics: the sources of a group are the
        // simulcast streams of one track, the first one's track; the others are its further
        // layers, each with its repair flows.
        for members in &groups.simulcast {
            let mut present = members
                .iter()
                .filter_map(|ssrc| slot_by_ssrc.get(ssrc).map(|&slot| (*ssrc, slot)));
            let Some((_, keeper)) = present.next() else {
                continue;
            };
            let layers: Vec<(SSRC, usize)> = present.collect();
            for (ssrc, slot) in layers {
                if slot == keeper || track_slots[slot].take().is_none() {
                    continue;
                }
                if let Some(track) = track_slots[keeper].as_mut() {
                    track.ssrc_layers.push(SsrcLayer {
                        ssrc,
                        rtx_ssrc: groups.rtx.get(&ssrc).copied(),
                        fec_ssrc: groups.fec.get(&ssrc).copied(),
                    });
                }
            }
        }

        let mut tracks_in_media_section: Vec<TrackDetails> =
            track_slots.into_iter().flatten().collect();
        // Every track of the section is in the streams its `a=msid` lines name; without such
        // lines, in the one its source-level msid names.
        let stream_ids_of = |stream_id: &str| -> Vec<MediaStreamId> {
            if has_media_msid {
                stream_ids.clone()
            } else if stream_id.is_empty() || stream_id == "-" {
                vec![]
            } else {
                vec![stream_id.to_owned()]
            }
        };
        for track in &mut tracks_in_media_section {
            if has_media_msid {
                // One track, whichever `a=ssrc` line it was read from.
                stream_id.clone_into(&mut track.stream_id);
                track_id.clone_into(&mut track.track_id);
            }
            track.stream_ids = stream_ids_of(&track.stream_id);
        }

        // If media line is using RTP Stream Identifier Source Description per RFC8851
        // the section is one track whose streams are its rids. Its `a=ssrc` lines (Firefox
        // and Pion write them beside 'rid' and 'simulcast') are kept on that track as the
        // SSRCs the section declares (RFC 9143 section 9.2): a packet that carries a RID is
        // bound by its rid, one that carries none by its declared SSRC.
        if has_media_msid || (!track_id.is_empty() && !stream_id.is_empty()) {
            // The streams the remote side sends: its `send` rids. A `recv` rid is one of this
            // endpoint's own streams, which the remote side takes.
            let rids: Vec<SimulcastRid> = get_rids(media, rid_ids)
                .into_iter()
                .filter(|rid| rid.direction == SimulcastDirection::Send)
                .collect();
            if !rids.is_empty() {
                let simulcast_track = TrackDetails {
                    mid: mid_value.to_string(),
                    kind: codec_type,
                    stream_id: stream_id.to_owned(),
                    stream_ids: stream_ids_of(stream_id),
                    track_id: track_id.to_owned(),
                    rids: rids.iter().map(|r| r.id.clone()).collect(),
                    rid_restrictions: rids
                        .iter()
                        .map(|r| (r.id.clone(), r.to_restrictions()))
                        .collect(),
                    // Each track's SSRC, then its further `SIM` streams: every one a
                    // declared primary with its own repair flows.
                    declared_ssrcs: tracks_in_media_section
                        .iter()
                        .flat_map(|track| {
                            track
                                .ssrc
                                .map(|ssrc| SsrcLayer {
                                    ssrc,
                                    rtx_ssrc: track.rtx_ssrc,
                                    fec_ssrc: track.fec_ssrc,
                                })
                                .into_iter()
                                .chain(track.ssrc_layers.iter().cloned())
                        })
                        .collect(),
                    ..Default::default()
                };

                tracks_in_media_section = vec![simulcast_track];
            } else if tracks_in_media_section.is_empty() {
                // no rids, no ssrc set
                let implicit_track = TrackDetails {
                    mid: mid_value.to_string(),
                    kind: codec_type,
                    stream_id: stream_id.to_owned(),
                    stream_ids: stream_ids_of(stream_id),
                    track_id: track_id.to_owned(),
                    ..Default::default()
                };

                tracks_in_media_section = vec![implicit_track];
            }
        }

        incoming_tracks.extend(tracks_in_media_section);
    }

    incoming_tracks
}

/// The `a=msid` lines of a media section (RFC 8830 section 2, `msid-id [SP msid-appdata]`):
/// the MediaStream ids they name, in order and once each, without the `-` that stands for
/// "no MediaStream" (RFC 8830 section 3), and the msid-appdata of the first line that has
/// one. `None` when the section has no well-formed `a=msid` line; a line that is not
/// `msid-id [SP msid-appdata]` is ignored (section 3: "SHOULD be ignored").
///
/// RFC 9429 section 5.8.2 reads the lines "ignoring appdata"; the appdata is still returned,
/// because a sender that writes it means its track id (RFC 8830 section 3).
pub(crate) fn media_msid(media: &MediaDescription) -> Option<(Vec<MediaStreamId>, String)> {
    let mut found = false;
    let mut stream_ids: Vec<MediaStreamId> = vec![];
    let mut track_id = String::new();
    for value in media
        .attributes
        .iter()
        .filter(|a| a.key == ATTR_KEY_MSID)
        .filter_map(|a| a.value.as_deref())
    {
        let mut tokens = value.split(' ');
        let (Some(id), appdata, None) = (tokens.next(), tokens.next(), tokens.next()) else {
            continue;
        };
        if !is_msid_token(id) || appdata.is_some_and(|appdata| !is_msid_token(appdata)) {
            continue;
        }
        found = true;
        if id != "-" && !stream_ids.iter().any(|known| known == id) {
            stream_ids.push(id.to_owned());
        }
        if let (true, Some(appdata)) = (track_id.is_empty(), appdata) {
            appdata.clone_into(&mut track_id);
        }
    }
    found.then_some((stream_ids, track_id))
}

#[test]
fn track_details_from_sdp_pairs_repair_flows_by_lookup() {
    const PRIMARIES: u32 = 3000;
    let mut media = MediaDescription::default()
        .with_value_attribute(ATTR_KEY_MID.to_owned(), "0".to_owned())
        .with_property_attribute(ATTR_KEY_SEND_RECV.to_owned());
    media.media_name.media = "video".to_owned();
    for i in 0..PRIMARIES {
        let (primary, rtx, fec) = (10_000 + i, 20_000 + i, 30_000 + i);
        // Half the groups follow their ssrc lines (the repair track is removed again), half
        // precede them (the repair ssrc is never added).
        let group_first = i % 2 == 0;
        if group_first {
            media = media
                .with_value_attribute(
                    ATTR_KEY_SSRC_GROUP.to_owned(),
                    format!("FID {primary} {rtx}"),
                )
                .with_value_attribute(
                    ATTR_KEY_SSRC_GROUP.to_owned(),
                    format!("FEC-FR {primary} {fec}"),
                );
        }
        for ssrc in [primary, rtx, fec] {
            media = media.with_value_attribute(
                ATTR_KEY_SSRC.to_owned(),
                format!("{ssrc} msid:stream track{i}"),
            );
        }
        if !group_first {
            media = media
                .with_value_attribute(
                    ATTR_KEY_SSRC_GROUP.to_owned(),
                    format!("FID {primary} {rtx}"),
                )
                .with_value_attribute(
                    ATTR_KEY_SSRC_GROUP.to_owned(),
                    format!("FEC-FR {primary} {fec}"),
                );
        }
    }
    let desc = SessionDescription::default().with_media(media);

    let tracks = track_details_from_sdp(&desc, RidIdGrammar::Corrected);

    assert_eq!(tracks.len(), PRIMARIES as usize);
    for (i, track) in tracks.iter().enumerate() {
        let i = i as u32;
        assert_eq!(track.ssrc, Some(10_000 + i));
        assert_eq!(track.rtx_ssrc, Some(20_000 + i));
        assert_eq!(track.fec_ssrc, Some(30_000 + i));
        assert_eq!(track.track_id, format!("track{i}"));
        assert_eq!(track.mid, "0");
    }
}

/// RFC 5576 section 4.2: a group "MAY list any number of additional" ids. A `FID` group of
/// three is a source and two further flows of it, the first of them its RTX flow; a `FEC-FR`
/// group of three is one source and two additive repair flows (RFC 5956 section 4.1). No flow
/// a group names as a repair flow is a track.
#[test]
fn groups_of_three_ids_name_one_source_and_its_flows() {
    let mut media = MediaDescription::default()
        .with_value_attribute(ATTR_KEY_MID.to_owned(), "0".to_owned())
        .with_property_attribute(ATTR_KEY_SEND_RECV.to_owned())
        .with_value_attribute(ATTR_KEY_SSRC_GROUP.to_owned(), "FID 4 14 24".to_owned())
        .with_value_attribute(ATTR_KEY_SSRC_GROUP.to_owned(), "FEC-FR 4 34 44".to_owned());
    media.media_name.media = "video".to_owned();
    for ssrc in [4, 14, 24, 34, 44] {
        media = media.with_value_attribute(
            ATTR_KEY_SSRC.to_owned(),
            format!("{ssrc} msid:stream track"),
        );
    }
    let tracks = track_details_from_sdp(
        &SessionDescription::default().with_media(media),
        RidIdGrammar::Corrected,
    );
    assert_eq!(tracks.len(), 1, "{tracks:?}");
    assert_eq!(tracks[0].ssrc, Some(4));
    assert_eq!(tracks[0].rtx_ssrc, Some(14));
    assert_eq!(tracks[0].fec_ssrc, Some(34));
    assert!(tracks[0].ssrc_layers.is_empty());
}

#[test]
fn get_rids_orders_and_pauses_by_lookup() {
    const RIDS: usize = 3000;
    let mut media = MediaDescription::default();
    media.media_name.media = "video".to_owned();
    for i in 0..RIDS {
        media = media.with_value_attribute(SDP_ATTRIBUTE_RID.to_owned(), format!("r{i} send"));
    }
    // Reverse order, every third one paused, and one unknown id.
    let mut list: Vec<String> = (0..RIDS)
        .rev()
        .map(|i| {
            if i % 3 == 0 {
                format!("~r{i}")
            } else {
                format!("r{i}")
            }
        })
        .collect();
    list.push("unknown".to_owned());
    let simulcast = media.clone().with_value_attribute(
        SDP_ATTRIBUTE_SIMULCAST.to_owned(),
        format!("send {}", list.join(";")),
    );

    let rids = get_rids(&simulcast, RidIdGrammar::Corrected);

    assert_eq!(rids.len(), RIDS);
    for (position, rid) in rids.iter().enumerate() {
        let i = RIDS - 1 - position;
        assert_eq!(rid.id, format!("r{i}"));
        assert_eq!(rid.paused, i % 3 == 0, "rid r{i}");
        assert!(rid.simulcast);
    }

    // RFC 8853 section 5.2: a rid-id "MUST NOT" occur twice on the line. One that does is
    // malformed and not used: the rids stay, in a=rid order, as no simulcast streams.
    list.push("r1".to_owned());
    let repeated = media.with_value_attribute(
        SDP_ATTRIBUTE_SIMULCAST.to_owned(),
        format!("send {}", list.join(";")),
    );
    let rids = get_rids(&repeated, RidIdGrammar::Corrected);
    assert_eq!(rids.len(), RIDS);
    assert!(
        rids.iter()
            .enumerate()
            .all(|(i, rid)| rid.id == format!("r{i}") && !rid.simulcast)
    );
}

/// `a=rtcp` (RFC 3605 section 2.1).
pub(crate) const ATTR_KEY_RTCP: &str = "rtcp";

/// The default candidate of a section (RFC 8839 section 4.2.1.2: the one "most likely to
/// work": a relayed candidate, else a server-reflexive one, else a host candidate; RTP,
/// component 1), as (address, port). UDP candidates are preferred, as the m= line says UDP.
/// A candidate whose address is not an IP address (an mDNS name) is never the default (the
/// mDNS ICE candidates draft, section 3.1.2.2: the `c=` line then says 0.0.0.0 and port 9).
fn default_candidate(candidates: &[RTCIceCandidate]) -> Option<(std::net::IpAddr, u16)> {
    use crate::peer_connection::transport::ice::candidate_type::RTCIceCandidateType as Type;
    use crate::peer_connection::transport::ice::protocol::RTCIceProtocol;
    let rank = |c: &RTCIceCandidate| -> u8 {
        match c.typ {
            Type::Relay => 0,
            Type::Srflx => 1,
            Type::Prflx => 2,
            _ => 3,
        }
    };
    candidates
        .iter()
        .filter_map(|c| Some((c, c.address.parse::<std::net::IpAddr>().ok()?)))
        .filter(|(c, _)| c.port != 0)
        .min_by_key(|(c, _)| {
            (
                c.protocol != RTCIceProtocol::Udp,
                rank(c),
                std::cmp::Reverse(c.priority),
            )
        })
        .map(|(c, ip)| (ip, c.port))
}

/// Puts a default destination in a section: the `m=` port and `c=` address, and the `a=rtcp`
/// line when the section has one (RTCP is multiplexed, so it is the RTP destination too; RFC
/// 5761 section 5.1.3).
pub(crate) fn set_default_destination(m: &mut MediaDescription, ip: std::net::IpAddr, port: u16) {
    m.media_name.port = RangedPort {
        value: port as isize,
        range: None,
    };
    let address_type = if ip.is_ipv4() { "IP4" } else { "IP6" };
    m.connection_information = vec![ConnectionInformation {
        network_type: "IN".to_owned(),
        address_type: address_type.to_owned(),
        address: Some(Address {
            address: ip.to_string(),
            ttl: None,
            range: None,
        }),
    }];
    for a in &mut m.attributes {
        if a.key == ATTR_KEY_RTCP {
            a.value = Some(format!("{port} IN {address_type} {ip}"));
        }
    }
}

/// RFC 9143 section 7.2 (and 7.5.1 for later offers): the bundled sections that are not
/// bundle-only share the BUNDLE transport's address and port, the default destination of the
/// section of their group that carries the candidates. Each BUNDLE group is a transport of its
/// own (section 5), with its own destination.
pub(crate) fn share_bundle_destination(d: &mut SessionDescription) {
    let groups: Vec<Vec<String>> = bundle_groups(d)
        .into_iter()
        .map(|group| group.into_iter().map(str::to_owned).collect())
        .collect();
    for group in groups {
        let in_group =
            |m: &MediaDescription| get_mid_value(m).is_some_and(|mid| group.contains(mid));
        let Some(carrier) = d.media_descriptions.iter().find(|m| {
            in_group(m) && m.attribute("candidate").is_some() && m.media_name.port.value != 0
        }) else {
            continue;
        };
        let Some(ip) = carrier
            .connection_information
            .first()
            .and_then(|c| c.address.as_ref())
            .and_then(|a| a.address.parse::<std::net::IpAddr>().ok())
        else {
            continue;
        };
        let Ok(port) = u16::try_from(carrier.media_name.port.value) else {
            continue;
        };
        if ip.is_unspecified() {
            continue;
        }
        for m in &mut d.media_descriptions {
            if m.media_name.port.value != 0 && !m.has_attribute(ATTR_KEY_BUNDLE_ONLY) && in_group(m)
            {
                set_default_destination(m, ip, port);
            }
        }
    }
}

pub(crate) fn add_candidates_to_media_descriptions(
    candidates: &[RTCIceCandidate],
    mut m: MediaDescription,
    ice_gathering_state: RTCIceGatheringState,
) -> Result<MediaDescription> {
    // Each line names its ICE generation with the `ufrag` extension attribute (RFC 8839
    // section 5.1 `extension-att-name`; RFC 8838 section 9: a candidate is tied to an ICE
    // session), the section's own `a=ice-ufrag`, as trickled candidates already do
    // (`usernameFragment`).
    let ufrag = m
        .attribute("ice-ufrag")
        .flatten()
        .filter(|ufrag| !ufrag.is_empty())
        .map(str::to_owned);
    let append_candidate_if_new = |c: &Candidate, m: MediaDescription| -> MediaDescription {
        let mut marshaled = c.marshal();
        if let Some(ufrag) = &ufrag {
            marshaled = format!("{marshaled} ufrag {ufrag}");
        }
        for a in &m.attributes {
            if let Some(value) = &a.value
                && &marshaled == value
            {
                return m;
            }
        }

        m.with_value_attribute("candidate".to_owned(), marshaled)
    };

    // RTP candidates only (component 1). RTP and RTCP are multiplexed on one port, so there
    // is no RTCP component to describe: RFC 8858 section 5.3 (updating RFC 8839), "the offerer
    // MUST NOT include RTCP candidates" when it cannot use a separate RTCP port, and RFC 5761
    // section 5.1.3 for the answer.
    for c in candidates {
        let mut candidate = c.to_ice()?;
        candidate.set_component(1);
        m = append_candidate_if_new(&candidate, m);
    }
    // RFC 8839 section 4.2.1.2 and RFC 9429 sections 5.2.2, 5.3.2: once there are candidates,
    // the m= and c= lines carry the default candidate's port and address (the dummy 9 and
    // 0.0.0.0 stand for "no candidates yet").
    if m.media_name.port.value != 0
        && let Some((ip, port)) = default_candidate(candidates)
    {
        set_default_destination(&mut m, ip, port);
    }

    if ice_gathering_state != RTCIceGatheringState::Complete {
        return Ok(m);
    }
    for a in &m.attributes {
        if &a.key == "end-of-candidates" {
            return Ok(m);
        }
    }

    Ok(m.with_property_attribute("end-of-candidates".to_owned()))
}

pub(crate) struct AddDataMediaSectionParams {
    should_add_candidates: bool,
    mid_value: String,
    ice_params: RTCIceParameters,
    dtls_role: ConnectionRole,
    ice_gathering_state: RTCIceGatheringState,
    sctp_max_message_size: usize,
    /// The `a=sctp-port` value (RFC 8841 section 5); 0 asks for no association.
    sctp_port: u16,
    /// Whether the m= line says `TCP/DTLS/SCTP`: in an answer, when the offer does (RFC 8841
    /// section 10.3: "an 'm=' line proto value identical to the value in the offer").
    sctp_over_tcp: bool,
}

pub(crate) fn add_data_media_section(
    d: SessionDescription,
    dtls_fingerprints: &[RTCDtlsFingerprint],
    candidates: &[RTCIceCandidate],
    params: AddDataMediaSectionParams,
) -> Result<SessionDescription> {
    let mut media = MediaDescription {
        media_name: MediaName {
            media: MEDIA_SECTION_APPLICATION.to_owned(),
            port: RangedPort {
                value: 9,
                range: None,
            },
            protos: vec![
                if params.sctp_over_tcp { "TCP" } else { "UDP" }.to_owned(),
                "DTLS".to_owned(),
                "SCTP".to_owned(),
            ],
            formats: vec!["webrtc-datachannel".to_owned()],
        },
        media_title: None,
        connection_information: vec![ConnectionInformation {
            network_type: "IN".to_owned(),
            address_type: "IP4".to_owned(),
            address: Some(Address {
                address: "0.0.0.0".to_owned(),
                ttl: None,
                range: None,
            }),
        }],
        bandwidth: vec![],
        encryption_key: None,
        attributes: vec![],
    }
    .with_value_attribute(
        ATTR_KEY_CONNECTION_SETUP.to_owned(),
        params.dtls_role.to_string(),
    )
    .with_value_attribute(ATTR_KEY_MID.to_owned(), params.mid_value)
    .with_property_attribute(RTCRtpTransceiverDirection::Sendrecv.to_string())
    .with_value_attribute("sctp-port".to_owned(), params.sctp_port.to_string())
    // RFC 8841 6.1: 0 would promise messages of any size, which this endpoint cannot take:
    // what it accepts is bounded by `SctpMaxMessageSize::MAX_MESSAGE_SIZE`, so that bound is
    // advertised instead, and it is the limit the SCTP transport receives by.
    .with_value_attribute(
        "max-message-size".to_owned(),
        format!(
            "{}",
            match params.sctp_max_message_size {
                0 => crate::peer_connection::configuration::setting_engine::SctpMaxMessageSize::MAX_MESSAGE_SIZE
                    as usize,
                limit => limit,
            }
        ),
    )
    .with_ice_credentials(
        params.ice_params.username_fragment,
        params.ice_params.password,
    );

    for f in dtls_fingerprints {
        media = media.with_fingerprint(f.algorithm.clone(), f.value.to_uppercase());
    }

    if params.should_add_candidates {
        media =
            add_candidates_to_media_descriptions(candidates, media, params.ice_gathering_state)?;
    }

    Ok(d.with_media(media))
}

