impl RTCPeerConnection {
    /// Each mid's first transceiver in `local_transceivers`, so a pass over every m-section of
    /// a description looks mids up instead of scanning the transceivers for each one.
    pub(crate) fn transceiver_index_by_mid(
        local_transceivers: &[RTCRtpTransceiverInternal],
    ) -> HashMap<String, usize> {
        let mut by_mid = HashMap::with_capacity(local_transceivers.len());
        for (i, t) in local_transceivers.iter().enumerate() {
            if let Some(mid) = t.mid() {
                by_mid.entry(mid.clone()).or_insert(i);
            }
        }
        by_mid
    }

    /// Given a direction+type pluck a transceiver from the passed list and return its index;
    /// `None` when no entry satisfies the requested type+direction
    pub(crate) fn satisfy_type_and_direction(
        remote_kind: RtpCodecKind,
        remote_direction: RTCRtpTransceiverDirection,
        local_transceivers: &[RTCRtpTransceiverInternal],
    ) -> Option<usize> {
        // Get direction order from most preferred to least
        let get_preferred_directions = || -> Vec<RTCRtpTransceiverDirection> {
            match remote_direction {
                RTCRtpTransceiverDirection::Sendrecv => vec![
                    RTCRtpTransceiverDirection::Recvonly,
                    RTCRtpTransceiverDirection::Sendrecv,
                ],
                RTCRtpTransceiverDirection::Sendonly => vec![RTCRtpTransceiverDirection::Recvonly],
                RTCRtpTransceiverDirection::Recvonly => vec![
                    RTCRtpTransceiverDirection::Sendonly,
                    RTCRtpTransceiverDirection::Sendrecv,
                ],
                _ => vec![],
            }
        };

        for possible_direction in get_preferred_directions() {
            // Find the index first to avoid multiple mutable borrows
            if let Some(index) = local_transceivers.iter().position(|t| {
                t.mid().is_none()
                    && !t.stopped()
                    && t.associable_with_remote_offer()
                    && t.kind() == remote_kind
                    && possible_direction == t.direction()
            }) {
                return Some(index);
            }
        }

        None
    }

    /// populate_sdp serializes a PeerConnections state into an SDP
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn populate_sdp(
        mut d: SessionDescription,
        dtls_fingerprints: &[RTCDtlsFingerprint],
        media_engine: &MediaEngine,
        transceivers: &mut [RTCRtpTransceiverInternal],
        candidates: &[RTCIceCandidate],
        ice_params: &RTCIceParameters,
        media_sections: &[MediaSection],
        params: PopulateSdpParams,
    ) -> Result<SessionDescription> {
        let media_dtls_fingerprints = if params.media_description_fingerprint {
            dtls_fingerprints.to_vec()
        } else {
            vec![]
        };

        // The mids of each BUNDLE group, in media section order.
        let mut bundled: Vec<Vec<String>> = vec![];
        // The media types (`audio`, `video`, `application`) of the sections so far that carry
        // their own transport parameters, for the bundle policy.
        let mut with_transport: Vec<String> = vec![];
        // Whether a section was made bundle-only (an initial offer).
        let mut any_bundle_only = false;

        let answer_payload_types = answer_payload_types(media_engine, media_sections);
        let mut candidates_added = false;
        let offers_over_tcp = params.bundle.is_offer() && params.sctp_over_tcp;
        for m in media_sections.iter() {
            // RFC 8829 §5.3.1: reflect rejected m-lines (port=0) in the answer.
            // These must appear in the same position as in the offer to preserve m-line indexing.
            if m.rejected {
                let (rejected_protos, rejected_formats) = if let Some(name) = &m.rejected_name {
                    (name.protos.clone(), name.formats.clone())
                } else if m.rejected_kind == "application" {
                    (
                        vec!["UDP".to_owned(), "DTLS".to_owned(), "SCTP".to_owned()],
                        vec!["webrtc-datachannel".to_owned()],
                    )
                } else {
                    (
                        vec![
                            "UDP".to_owned(),
                            "TLS".to_owned(),
                            "RTP".to_owned(),
                            "SAVPF".to_owned(),
                        ],
                        vec!["0".to_owned()],
                    )
                };

                d = d.with_media(
                    MediaDescription {
                        media_name: MediaName {
                            media: m.rejected_kind.clone(),
                            port: RangedPort {
                                value: 0,
                                range: None,
                            },
                            protos: rejected_protos,
                            formats: rejected_formats,
                        },
                        media_title: None,
                        connection_information: vec![ConnectionInformation {
                            network_type: "IN".to_owned(),
                            address_type: "IP4".to_owned(),
                            address: Some(Address {
                                address: "0.0.0.0".to_owned(),
                                ttl: None,
                                range: None,
                            }),
                        }],
                        bandwidth: vec![],
                        encryption_key: None,
                        attributes: vec![],
                    }
                    .with_value_attribute(ATTR_KEY_MID.to_owned(), m.mid.clone()),
                );
                if let (Some(protos), Some(desc)) =
                    (&m.offered_protos, d.media_descriptions.last_mut())
                {
                    desc.media_name.protos.clone_from(protos);
                }
                if m.stopped
                    && let Some(desc) = d.media_descriptions.last_mut()
                {
                    let rejected = std::mem::take(desc);
                    *desc = rejected.with_property_attribute("inactive".to_owned());
                }
                continue; // rejected m-lines are not added to BUNDLE
            }

            if m.data && m.transceiver_index != usize::MAX {
                return Err(Error::ErrSDPMediaSectionMediaDataChanInvalid);
            } else if !m.data && m.transceiver_index >= transceivers.len() {
                return Err(Error::ErrSDPMediaSectionTrackInvalid);
            }

            let should_add_candidates = !candidates_added;

            let should_add_id = if m.data {
                let params = AddDataMediaSectionParams {
                    should_add_candidates,
                    mid_value: m.mid.clone(),
                    ice_params: ice_params.clone(),
                    dtls_role: params.connection_role,
                    ice_gathering_state: params.ice_gathering_state,
                    sctp_max_message_size: params.sctp_max_message_size,
                    sctp_port: params.sctp_port,
                    sctp_over_tcp: params.sctp_over_tcp,
                };
                d = add_data_media_section(d, &media_dtls_fingerprints, candidates, params)?;
                true
            } else if let Some(section) = &m.fec {
                let kind = transceivers[m.transceiver_index].kind().to_string();
                d = fec_session::add_fec_media_section(
                    d,
                    &media_dtls_fingerprints,
                    candidates,
                    fec_session::AddFecMediaSectionParams {
                        should_add_candidates,
                        mid_value: m.mid.clone(),
                        kind,
                        ice_params,
                        dtls_role: params.connection_role,
                        ice_gathering_state: params.ice_gathering_state,
                        section,
                    },
                )?;
                true
            } else {
                let params = AddTransceiverSdpParams {
                    should_add_candidates,
                    mid_value: m.mid.clone(),
                    dtls_role: params.connection_role,
                    ice_gathering_state: params.ice_gathering_state,
                    ignore_rid_pause_for_recv: params.ignore_rid_pause_for_recv,
                    rid_pause_marks: params.rid_pause_marks,
                    video_receive_limits: params.video_receive_limits,
                    codec_video_receive_limits: params.codec_video_receive_limits.clone(),
                    w3c_simulcast_answer: params.w3c_simulcast_answer,
                    msid_appdata: params.msid_appdata,
                    write_ssrc_attributes_for_simulcast: params.write_ssrc_attributes_for_simulcast,
                    is_offer: params.bundle.is_offer(),
                    rtcp_mux_only: params.rtcp_mux_only,
                    rtcp_mux_only_renegotiated: params.rtcp_mux_only_renegotiated,
                    ecn: params.ecn,
                    answer_payload_types: answer_payload_types.clone(),
                    answer_offered_formats_only: params.answer_offered_formats_only,
                };
                let (d1, should_add_id) = RTCPeerConnection::add_transceiver_sdp(
                    d,
                    &media_dtls_fingerprints,
                    media_engine,
                    transceivers,
                    ice_params,
                    candidates,
                    m,
                    params,
                )?;
                d = d1;
                // RFC 9429 section 5.1.2: the offered profile "is determined by the protocol
                // associated with the current default or selected ICE candidate", as for the
                // data section (`sctp_over_tcp`, RFC 8841 section 12.2): `TCP/DTLS/RTP/SAVPF`
                // (RFC 7850) when that candidate is a TCP one. An answer repeats the offer's.
                if offers_over_tcp
                    && let Some(desc) = d.media_descriptions.last_mut()
                    && desc.media_name.protos == ["UDP", "TLS", "RTP", "SAVPF"]
                {
                    desc.media_name.protos =
                        ["TCP", "DTLS", "RTP", "SAVPF"].map(str::to_owned).to_vec();
                    // RFC 6679 section 6.1.3: `a=ecn-capable-rtp` "MUST NOT be used for RTP
                    // sessions using TCP".
                    desc.attributes
                        .retain(|a| a.key != ecn::ATTR_KEY_ECN_CAPABLE_RTP);
                }
                should_add_id
            };

            candidates_added = true;

            if let (Some(protos), Some(desc)) = (&m.offered_protos, d.media_descriptions.last_mut())
            {
                if m.data && protos.as_slice() == ["DTLS", "SCTP"] {
                    into_legacy_data_section(desc);
                } else {
                    desc.media_name.protos.clone_from(protos);
                    // An RTP section offered with a profile without feedback (`RTP/SAVP`, not
                    // `.../SAVPF`) is answered without it: no `a=rtcp-fb` (RFC 4585 section
                    // 4.1: the feedback attributes are for the AVPF profiles) and no reduced
                    // size RTCP (RFC 5506 section 4: reduced-size RTCP "MUST only be used"
                    // with AVPF / SAVPF). The answer says what the session then negotiates.
                    if !m.data
                        && !protos.iter().any(|p| {
                            p.eq_ignore_ascii_case("AVPF") || p.eq_ignore_ascii_case("SAVPF")
                        })
                    {
                        desc.attributes
                            .retain(|a| a.key != ATTR_KEY_RTCP_FB && a.key != ATTR_KEY_RTCPRSIZE);
                    }
                }
            }

            if should_add_id {
                let media_type = d
                    .media_descriptions
                    .last()
                    .map(|desc| desc.media_name.media.clone())
                    .unwrap_or_default();
                // Whether the bundle policy leaves this section without a transport of its
                // own, given the sections before it (RFC 9429 section 4.1.1): `balanced`
                // (the default), "the second and any subsequent 'm=' sections of each type";
                // `must-bundle` (`max-bundle`), "all streams other than the first";
                // `max-compat`, none. An RTP section needs an RTP section before it to take
                // its BUNDLE attributes from (RFC 9143 section 9.3.1.1).
                let rtp = media_type != MEDIA_SECTION_APPLICATION;
                let has_carrier = if rtp {
                    with_transport
                        .iter()
                        .any(|t| t != MEDIA_SECTION_APPLICATION)
                } else {
                    !with_transport.is_empty()
                };
                let without_transport = has_carrier
                    && match params.bundle_policy {
                        RTCBundlePolicy::MaxCompat => false,
                        RTCBundlePolicy::MustBundle => true,
                        _ => with_transport.contains(&media_type),
                    };
                let group = params.bundle.group_of(&m.mid);
                let join = |bundled: &mut Vec<Vec<String>>, index: usize| {
                    if bundled.len() <= index {
                        bundled.resize(index + 1, vec![]);
                    }
                    bundled[index].push(m.mid.clone());
                };
                match &params.bundle {
                    BundleMode::Offer { .. } => {
                        // A section the offer leaves outside every group has a transport of
                        // its own, so it is never bundle-only (RFC 9143 section 6: a
                        // bundle-only section is one of the BUNDLE group).
                        if params.initial_offer
                            && without_transport
                            && group.is_some()
                            && let Some(desc) = d.media_descriptions.last_mut()
                        {
                            make_bundle_only(desc, params.bundle_only_browser_form);
                            any_bundle_only = true;
                        } else {
                            with_transport.push(media_type);
                        }
                        // A section the most recent answer accepted outside every group stays
                        // outside: it keeps its transport (RFC 9143 section 7.5).
                        if let Some(index) = group {
                            join(&mut bundled, index);
                        }
                    }
                    BundleMode::Answer(_) if group.is_some() => {
                        join(&mut bundled, group.unwrap_or_default());
                    }
                    BundleMode::Answer(offered)
                        if !offered.is_empty()
                            && params.bundle_policy != RTCBundlePolicy::MustBundle =>
                    {
                        // Outside the offered group: it has a transport of its own (RFC 9143
                        // section 7.3.2; `RTCPeerConnection::apply_transport_layout`).
                        with_transport.push(media_type);
                    }
                    BundleMode::Answer(offered) if !offered.is_empty() => {
                        // Outside the offered group under `must-bundle`: no transport but the
                        // BUNDLE one (RFC 9429 section 4.1.1).
                        if let Some(desc) = d.media_descriptions.last_mut()
                            && reject_written_section(desc)
                        {
                            candidates_added = false;
                        }
                    }
                    // No BUNDLE group offered: every accepted section is a transport of its
                    // own, and the policy says how many this endpoint takes (RFC 9429 section
                    // 4.1.1: balanced "will reject all but the first 'm=' section of each
                    // type", must-bundle "any 'm=' sections other than the first").
                    BundleMode::Answer(_) => {
                        if without_transport {
                            if let Some(desc) = d.media_descriptions.last_mut()
                                && reject_written_section(desc)
                            {
                                candidates_added = false;
                            }
                        } else {
                            with_transport.push(media_type);
                        }
                    }
                }
            }
        }

        // RFC 8122 section 5: "The fingerprint attribute may be either a session-level or a
        // media-level SDP attribute"; RFC 9429 section 5.2.1: the m= sections "MUST all have the
        // same fingerprint value or values [RFC8122], or these values MUST be session-level
        // attributes". With the setting, an initial offer with a bundle-only section has them at
        // session level as well, so the bundle-only sections (which carry none, RFC 9143 7.1.3)
        // see one: Chromium and WebKit otherwise answer a bundle-only data section with port
        // zero, and Firefox does not apply the offer.
        if !params.media_description_fingerprint
            || (params.bundle_only_browser_form && any_bundle_only)
        {
            for fingerprint in dtls_fingerprints {
                d = d.with_fingerprint(
                    fingerprint.algorithm.clone(),
                    fingerprint.value.to_uppercase(),
                );
            }
        }

        // RFC 8445 section 10: "an agent compliant to this specification MUST inform the
        // peer about the compliance using the 'ice2' option" (RFC 8839 section 5.6:
        // `a=ice-options`), lite agents included. `trickle` too: this side accepts trickled
        // candidates (`add_remote_candidate` at any time after the remote description) and
        // trickles its own (JSEP RFC 9429 §5.2.1 / §5.3.1), and RFC 8840 §4: "Trickle ICE
        // Agents MUST indicate support for Trickle ICE by including the ice-option "trickle"
        // within all SDP Offers and Answers". A lite agent is one as well: it takes trickled
        // candidates and trickles its own (its TCP candidates come after the description),
        // and RFC 8838 Appendix B has an ICE-lite agent capable of Trickle ICE "indicate
        // support for Trickle ICE". Without it the full peer takes the lite agent's
        // description for all its candidates (W3C webrtc-pc 5.6.4, `canTrickleIceCandidates`
        // false) and may report "failed" before the trickled ones arrive.
        if params.is_ice_lite {
            // RFC 8839 §5.3
            d = d.with_property_attribute(ATTR_KEY_ICELITE.to_owned());
        }
        // Offers say `trickle ice2`, lite agents' too. An answer says what
        // `SettingEngineBuilder::with_answer_ice_options` gives: by default RFC 9429 section
        // 5.3.1's form, each of the two only "if such an option was present in the offer",
        // against RFC 8840 section 4.1.3 and RFC 8445 section 10 (`answer_ice_options`;
        // spec-issues row 28). No line for no option (RFC 8839 section 5.6: one or more tags).
        let ice_options = params.ice_options.join(" ");
        // RFC 8839 section 5.6: "session-level or media-level".
        if ice_options.is_empty() {
            // Nothing to say: no line.
        } else if params.ice_options_in_media_sections {
            for media in &mut d.media_descriptions {
                if let Some(at) = media.attributes.iter().position(|a| a.key == "ice-pwd") {
                    media.attributes.insert(
                        at + 1,
                        sdp::description::common::Attribute::new(
                            ATTR_KEY_ICE_OPTIONS.to_owned(),
                            Some(ice_options.clone()),
                        ),
                    );
                }
            }
        } else {
            d = d.with_value_attribute(ATTR_KEY_ICE_OPTIONS.to_owned(), ice_options);
        }
        // RFC 8445 section 14.2: an agent that wants a Ta other than the default "MUST
        // indicate the proposed value to its peer"; RFC 8839 section 5.5: `a=ice-pacing`, in
        // milliseconds, at session level.
        if let Some(ta) = params.ice_pacing {
            d = d.with_value_attribute(ATTR_KEY_ICE_PACING.to_owned(), ta.as_millis().to_string());
        }

        if params.is_extmap_allow_mixed {
            // RFC 8285 6.
            d = d.with_property_attribute(ATTR_KEY_EXTMAP_ALLOW_MIXED.to_owned());
        }

        bundled.retain(|group| !group.is_empty());
        if let BundleMode::Answer(offered) = &params.bundle {
            // The offer's order: each group's first accepted tag is its answerer-tagged
            // section.
            for group in bundled.iter_mut() {
                if let Some(tags) = offered
                    .iter()
                    .find(|tags| group.first().is_some_and(|mid| tags.contains(mid)))
                {
                    group.sort_by_key(|mid| tags.iter().position(|tag| tag == mid));
                }
            }
        }
        for (index, bundled) in bundled.iter().enumerate() {
            if index == 0
                && params.offered_tag_rtcp_mux_only
                && let Some(tag) = bundled.first()
                && let Some(tagged) = d.media_descriptions.iter_mut().find(|media| {
                    get_mid_value(media) == Some(tag)
                        && media.has_attribute(ATTR_KEY_RTCPMUX)
                        && !media.has_attribute(ATTR_KEY_RTCP_MUX_ONLY)
                })
            {
                let at = tagged
                    .attributes
                    .iter()
                    .position(|a| a.key == ATTR_KEY_RTCPMUX)
                    .map_or(tagged.attributes.len(), |i| i + 1);
                tagged.attributes.insert(
                    at,
                    sdp::description::common::Attribute::new(
                        ATTR_KEY_RTCP_MUX_ONLY.to_owned(),
                        None,
                    ),
                );
            }
            // RFC 9143 section 7.1.3: in an answer or a subsequent offer only the tagged section
            // (the first of the group) carries the BUNDLE attributes, unless the application
            // asked for the browsers' repeated form.
            if params.bundle_attributes_in_tagged_section_only && !params.initial_offer {
                // The tagged section speaks for the group, also when it is not RTP itself (RFC
                // 9143 section 7.1.3, the note: "the tagged 'm=' section might contain an SDP
                // 'rtcp-mux' attribute even if the tagged 'm=' section does not describe
                // RTP-based media"; section 9.3.1.2: "MUST include an SDP 'rtcp-mux' attribute
                // in the answerer-tagged 'm=' section"). So when the tagged section is the data
                // section it takes `a=rtcp-mux` from the RTP sections that are about to lose it,
                // and `a=rtcp-rsize` when each of them has it.
                let others: Vec<&MediaDescription> = bundled
                    .iter()
                    .skip(1)
                    .filter_map(|mid| {
                        d.media_descriptions
                            .iter()
                            .find(|media| get_mid_value(media) == Some(mid))
                    })
                    .filter(|media| media.media_name.media != MEDIA_SECTION_APPLICATION)
                    .collect();
                let mux = others
                    .iter()
                    .any(|media| media.has_attribute(ATTR_KEY_RTCPMUX));
                let rsize = !others.is_empty()
                    && others
                        .iter()
                        .all(|media| media.has_attribute(ATTR_KEY_RTCPRSIZE));
                if let Some(tagged) = bundled.first().and_then(|tag| {
                    d.media_descriptions
                        .iter_mut()
                        .find(|media| get_mid_value(media) == Some(tag))
                }) && tagged.media_name.media == MEDIA_SECTION_APPLICATION
                {
                    for (key, wanted) in [(ATTR_KEY_RTCPMUX, mux), (ATTR_KEY_RTCPRSIZE, rsize)] {
                        if wanted && !tagged.has_attribute(key) {
                            tagged
                                .attributes
                                .push(sdp::description::common::Attribute::new(
                                    key.to_owned(),
                                    None,
                                ));
                        }
                    }
                }
                for mid in bundled.iter().skip(1) {
                    if let Some(media) = d
                        .media_descriptions
                        .iter_mut()
                        .find(|media| get_mid_value(media) == Some(mid))
                    {
                        media.attributes.retain(|a| {
                            !BUNDLE_ATTRIBUTES.contains(&a.key.as_str())
                                && a.key != "end-of-candidates"
                        });
                    }
                }
            }
        }
        for group in &bundled {
            d = d.with_value_attribute(
                ATTR_KEY_GROUP.to_owned(),
                format!("BUNDLE {}", group.join(" ")),
            );
        }
        // RFC 5109 sections 14.1 and 14.3: a FEC session is grouped with the media section it
        // protects (RFC 5888, with the FEC-FR semantics of RFC 5956 or the FEC semantics of
        // RFC 4756), in an offer and, when the answerer accepts it, "by including the same
        // grouping in the answer". Only while both sections are accepted: a group names no
        // rejected section (RFC 5888 section 9.2).
        let accepted = |mid: &str| {
            d.media_descriptions.iter().any(|media| {
                get_mid_value(media).is_some_and(|m| m == mid) && !is_rejected_media(media)
            })
        };
        let fec_groups: Vec<String> = media_sections
            .iter()
            .filter(|m| !m.rejected)
            .filter_map(|m| m.fec.as_ref().map(|fec| (m, fec)))
            .filter(|(m, fec)| accepted(&m.mid) && accepted(&fec.protected_mid))
            .map(|(m, fec)| fec_session::fec_group_value(fec.semantics, &fec.protected_mid, &m.mid))
            .collect();
        for group in fec_groups {
            d = d.with_value_attribute(ATTR_KEY_GROUP.to_owned(), group);
        }

        // After ICE selected a pair: the sections that carry the candidates name it.
        for m in &mut d.media_descriptions {
            if m.media_name.port.value == 0 || m.attribute("candidate").is_none() {
                continue;
            }
            if let Some((ip, port)) = params.selected_destination {
                set_default_destination(m, ip, port);
            }
            for value in &params.remote_candidates {
                m.attributes.push(sdp::description::common::Attribute::new(
                    ATTR_KEY_REMOTE_CANDIDATES.to_owned(),
                    Some(value.clone()),
                ));
            }
        }
        share_bundle_destination(&mut d);

        // Lip synchronization groups (RFC 5888 section 7; RFC 9429 sections 5.2.1, 5.2.2,
        // 5.3.1), of the accepted RTP sections.
        let live: Vec<(String, Vec<String>)> = media_sections
            .iter()
            .filter(|m| !m.rejected && !m.data && m.transceiver_index < transceivers.len())
            .filter(|m| {
                d.media_descriptions.iter().any(|media| {
                    get_mid_value(media) == Some(&m.mid)
                        && (media.media_name.port.value != 0
                            || media.has_attribute(ATTR_KEY_BUNDLE_ONLY))
                })
            })
            .map(|m| {
                let streams = transceivers[m.transceiver_index]
                    .sender()
                    .as_ref()
                    .map(|sender| sender.associated_streams().to_vec())
                    .unwrap_or_default();
                (m.mid.clone(), streams)
            })
            .collect();
        for group in generated_ls_groups(&live, &params.ls_groups, params.bundle.is_offer()) {
            d = d
                .with_value_attribute(ATTR_KEY_GROUP.to_owned(), format!("LS {}", group.join(" ")));
        }
        make_msid_pairs_unique(&mut d);

        // `SettingEngineBuilder::with_bundle_only_sections_in_browser_form`: each bundle-only
        // section says its group's ICE credentials (the tagged section's), against RFC 9429
        // section 5.2.1 ("Bundle-only "m=" sections MUST NOT contain any ICE credentials") and
        // RFC 9143 section 7.1.3. Firefox compares each m= section's credentials in a later
        // remote description with the ones of the current one (JsepSessionImpl
        // IceCredentialsDiffer) and takes the credentials a later answer repeats in a section
        // that had none for an ICE restart; it also refuses a later description without them
        // in every section ("no ice-ufrag attribute at level 1"), so the tagged-only form of
        // RFC 9143 7.1.3 for later descriptions does not help (test-env run 45908363443).
        if params.bundle_only_browser_form && any_bundle_only {
            let credentials: Vec<Option<(String, String)>> = d
                .media_descriptions
                .iter()
                .map(|media| {
                    if !media.has_attribute(ATTR_KEY_BUNDLE_ONLY) {
                        return None;
                    }
                    let tagged = tagged_section(&d, media)?;
                    Some((
                        tagged.attribute("ice-ufrag")??.to_owned(),
                        tagged.attribute("ice-pwd")??.to_owned(),
                    ))
                })
                .collect();
            for (media, credentials) in d.media_descriptions.iter_mut().zip(credentials) {
                let Some((ufrag, pwd)) = credentials else {
                    continue;
                };
                let at = media
                    .attributes
                    .iter()
                    .position(|a| a.key == ATTR_KEY_BUNDLE_ONLY)
                    .unwrap_or(media.attributes.len());
                media.attributes.insert(
                    at,
                    sdp::description::common::Attribute::new("ice-pwd".to_owned(), Some(pwd)),
                );
                media.attributes.insert(
                    at,
                    sdp::description::common::Attribute::new("ice-ufrag".to_owned(), Some(ufrag)),
                );
            }
        }

        Ok(d)
    }
}

pub(crate) fn get_mid_value(media: &MediaDescription) -> Option<&String> {
    for attr in &media.attributes {
        if attr.key == "mid" {
            return attr.value.as_ref();
        }
    }
    None
}

pub(crate) fn get_peer_direction(media: &MediaDescription) -> RTCRtpTransceiverDirection {
    for a in &media.attributes {
        let direction = RTCRtpTransceiverDirection::from(a.key.as_str());
        if direction != RTCRtpTransceiverDirection::Unspecified {
            return direction;
        }
    }
    RTCRtpTransceiverDirection::Unspecified
}

/// The `a=tls-id` attribute of RFC 8842 section 4.
pub(crate) const ATTR_KEY_TLS_ID: &str = "tls-id";

/// RFC 8842 section 4: `tls-id-value = 20*255(tls-id-char)`,
/// `tls-id-char = ALPHA / DIGIT / "+" / "/" / "-" / "_"`.
pub(crate) fn is_valid_tls_id(value: &str) -> bool {
    (20..=255).contains(&value.len())
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"+/-_".contains(&b))
}

/// The remote `a=tls-id` (RFC 8842 section 4), if the description has one.
///
/// The attribute is media-level and its multiplexing category is IDENTICAL: it sits on the
/// BUNDLE-tag m-section, and any other section that repeats it must give the same value. A
/// value outside the syntax, or two sections of the one transport that disagree, make the
/// description [`Error::ErrSessionDescriptionInvalidTlsId`]. No peer is required to send it.
///
/// Each transport is a DTLS association of its own (RFC 8842 section 5), so sections on
/// different transports may state different values: sections are on one transport when they
/// share ICE credentials (an initial BUNDLE offer gives each section that is not bundle-only
/// its own, RFC 9143 section 7.2; a section outside every group has its own). The value
/// returned is the first section's that states one: the description (or the part of it,
/// `transport_layout::description_for`) the caller sets up starts with its transport.
pub(crate) fn extract_tls_id(desc: &SessionDescription) -> Result<Option<String>> {
    let mut first: Option<&str> = None;
    let mut by_transport: HashMap<Option<&str>, &str> = HashMap::new();
    for m in &desc.media_descriptions {
        for attribute in m.attributes.iter().filter(|a| a.key == ATTR_KEY_TLS_ID) {
            let value = attribute
                .value
                .as_deref()
                .filter(|value| is_valid_tls_id(value))
                .ok_or(Error::ErrSessionDescriptionInvalidTlsId)?;
            if is_rejected_media(m) {
                continue;
            }
            let (ufrag, _) = media_ice_credentials(desc, m);
            if by_transport
                .insert(ufrag, value)
                .is_some_and(|earlier| earlier != value)
            {
                return Err(Error::ErrSessionDescriptionInvalidTlsId);
            }
            first.get_or_insert(value);
        }
    }
    Ok(first.map(str::to_owned))
}

/// Whether the description has an RTP media section that is not rejected: such a session needs
/// SRTP keys from the DTLS association (RFC 5764, RFC 8827 section 6.5).
pub(crate) fn has_rtp_media(desc: &SessionDescription) -> bool {
    desc.media_descriptions
        .iter()
        .any(|m| !is_rejected_media(m) && matches!(m.media_name.media.as_str(), "audio" | "video"))
}

/// Checks the syntax of every DTLS attribute of a remote description, at session level and in
/// every m-section, before any of the description is applied: `a=fingerprint` (RFC 8122 section
/// 5), `a=setup` (RFC 4145 section 4, RFC 8842 section 5.1) and `a=tls-id` (RFC 8842 section
/// 4). Whether the description has the fingerprints it needs is [`extract_fingerprints`]'s
/// question.
pub(crate) fn validate_dtls_attributes(
    desc: &SessionDescription,
    accept_lowercase_fingerprints: bool,
) -> Result<()> {
    let fingerprints = |attributes: &[sdp::description::common::Attribute]| -> Result<()> {
        for attribute in attributes.iter().filter(|a| a.key == "fingerprint") {
            parse_fingerprint_attribute(
                attribute
                    .value
                    .as_deref()
                    .ok_or(Error::ErrSessionDescriptionInvalidFingerprint)?,
                accept_lowercase_fingerprints,
            )?;
        }
        Ok(())
    };
    fingerprints(&desc.attributes)?;
    for m in &desc.media_descriptions {
        fingerprints(&m.attributes)?;
    }
    validate_setup_attributes(desc)?;
    // Every `tls-id` is well formed, a rejected section's too (RFC 8842 section 4).
    for m in &desc.media_descriptions {
        for attribute in m.attributes.iter().filter(|a| a.key == ATTR_KEY_TLS_ID) {
            if !attribute.value.as_deref().is_some_and(is_valid_tls_id) {
                return Err(Error::ErrSessionDescriptionInvalidTlsId);
            }
        }
    }
    // One `tls-id` per transport (RFC 8842 section 5): each BUNDLE group and each section
    // outside one is checked on its own.
    let groups = crate::peer_connection::transport_layout::transport_groups(desc);
    if groups.is_empty() {
        extract_tls_id(desc)?;
    }
    for group in groups {
        extract_tls_id(&crate::peer_connection::transport_layout::description_for(
            desc, &group,
        ))?;
    }
    Ok(())
}

/// Extracts the remote DTLS fingerprints (RFC 8122 §5).
///
/// A section carries one `a=fingerprint` line per certificate and hash function (W3C
/// `RTCPeerConnection` writes one for each of its certificates), and the peer's certificate must
/// match one of them, so all of them are returned, the sha-256 ones first (which of them DTLS
/// verification uses is `preferred_fingerprints`' choice).
///
/// "If it is a session-level attribute, it applies to all TLS sessions for which no media-level
/// fingerprint attribute is defined": each m-section that is not rejected has its own
/// fingerprints, or the session-level ones when it has none. All of them share one transport,
/// so their sets must agree on the sha-256 values when they have any (else on every value), or
/// the description is [`Error::ErrSessionDescriptionConflictingFingerprints`]; a session-level
/// set that every section overrides applies to nothing and is not compared. A value that does
/// not follow the attribute's syntax is [`Error::ErrSessionDescriptionInvalidFingerprint`],
/// wherever it sits.
///
/// With BUNDLE, `a=fingerprint` is of the TRANSPORT category (RFC 8859 section 4.5 and
/// appendix A): the group's transport is set up from its tagged section, so that section's
/// fingerprints are the group's, and what the other bundled sections carry is not used (RFC
/// 9143 section 7.1.3: their transport attributes are the offerer's proposal for transports
/// BUNDLE replaces). They are therefore not compared, unless
/// [`check_bundled_fingerprints_agree`] is asked for.
pub(crate) fn extract_fingerprints(desc: &SessionDescription) -> Result<Vec<RTCDtlsFingerprint>> {
    fingerprints_in_force(desc, false)
}

/// The hardening of `SettingEngineBuilder::with_bundled_fingerprints_agreeing`: every bundled
/// section's fingerprints must agree with the tagged section's, as those of sections outside
/// the group already must ([`Error::ErrSessionDescriptionConflictingFingerprints`]). Stricter
/// than RFC 8859 section 4.5, which takes the tagged section's and ignores the others.
pub(crate) fn check_bundled_fingerprints_agree(desc: &SessionDescription) -> Result<()> {
    fingerprints_in_force(desc, true).map(|_| ())
}

fn fingerprints_in_force(
    desc: &SessionDescription,
    every_bundled_section: bool,
) -> Result<Vec<RTCDtlsFingerprint>> {
    let parse =
        |attributes: &[sdp::description::common::Attribute]| -> Result<Vec<RTCDtlsFingerprint>> {
            let mut fingerprints = vec![];
            for attribute in attributes.iter().filter(|a| a.key == "fingerprint") {
                fingerprints.push(parse_fingerprint_attribute(
                    attribute
                        .value
                        .as_deref()
                        .ok_or(Error::ErrSessionDescriptionInvalidFingerprint)?,
                    // The case of the digits is `validate_dtls_attributes`' question.
                    true,
                )?);
            }
            // sha-256 first; the order within an algorithm is kept.
            fingerprints.sort_by_key(|f| !f.algorithm.eq_ignore_ascii_case("sha-256"));
            Ok(fingerprints)
        };
    let compared = |fingerprints: &[RTCDtlsFingerprint]| -> Vec<(String, String)> {
        let has_sha256 = fingerprints
            .iter()
            .any(|f| f.algorithm.eq_ignore_ascii_case("sha-256"));
        let mut set: Vec<(String, String)> = fingerprints
            .iter()
            .filter(|f| !has_sha256 || f.algorithm.eq_ignore_ascii_case("sha-256"))
            .map(|f| (f.algorithm.to_lowercase(), f.value.to_lowercase()))
            .collect();
        set.sort();
        set.dedup();
        set
    };

    let session_level = parse(&desc.attributes)?;
    // The fingerprints in force for each m-section that has a transport, and those of the
    // rejected ones, which only count when nothing else gives any.
    let mut in_force = vec![];
    let mut rejected = vec![];
    for m in &desc.media_descriptions {
        let media_level = parse(&m.attributes)?;
        // A bundled section other than its group's tagged one: its transport attributes are
        // not the group's (RFC 8859 section 4.5). Still parsed, so a malformed value refuses
        // the description wherever it sits.
        let untagged = tagged_section(desc, m).is_some_and(|tagged| !std::ptr::eq(tagged, m));
        if is_rejected_media(m) {
            rejected.push(media_level);
        } else if untagged && !every_bundled_section {
            continue;
        } else if media_level.is_empty() {
            in_force.push(session_level.clone());
        } else {
            in_force.push(media_level);
        }
    }
    in_force.retain(|level| !level.is_empty());
    if in_force.is_empty() {
        in_force.push(session_level);
        in_force.append(&mut rejected);
        in_force.retain(|level| !level.is_empty());
    }

    let Some(first) = in_force.first() else {
        return Err(Error::ErrSessionDescriptionNoFingerprint);
    };
    let expected = compared(first);
    if in_force[1..]
        .iter()
        .any(|level| compared(level) != expected)
    {
        return Err(Error::ErrSessionDescriptionConflictingFingerprints);
    }

    Ok(in_force.swap_remove(0))
}

/// RFC 8830 section 2: "Multiple media descriptions with the same value for 'msid-id' and
/// 'msid-appdata' are not permitted". W3C webrtc-pc lets one track be sent by several
/// transceivers (`addTransceiver(track)` twice), and the appdata this endpoint writes is the
/// track id (`with_msid_appdata`), so two sections would carry the same pair. Both allow
/// distinct appdata: a section whose `a=msid` repeats an earlier section's pair has its
/// appdata (and its source-level `msid`) made unique with a suffix, `<track id>-<n>`, kept
/// within the 64 token characters. The same sections give the same result every time, so a
/// later offer keeps the lines (RFC 9429 section 5.2.2). A line without appdata (the RFC 9429
/// form) is not a pair: the RFC 9429 section 5.2.1 examples have one stream in two sections.
fn make_msid_pairs_unique(desc: &mut SessionDescription) {
    let mut used: HashSet<(String, String)> = HashSet::new();
    for media in &mut desc.media_descriptions {
        // The line is `a=msid:<id> <appdata>`: written as a property attribute whose key
        // holds it all (`add_sender_sdp`), or parsed as key `msid` and a value.
        let msid_value = |a: &sdp::description::common::Attribute| -> Option<String> {
            if a.key == "msid" {
                a.value.clone()
            } else {
                a.key
                    .strip_prefix("msid:")
                    .filter(|_| a.value.is_none())
                    .map(str::to_owned)
            }
        };
        let pairs: Vec<(String, String)> = media
            .attributes
            .iter()
            .filter_map(|a| {
                let value = msid_value(a)?;
                let (id, appdata) = value.split_once(' ')?;
                Some((id.to_owned(), appdata.to_owned()))
            })
            .collect();
        let Some(appdata) = pairs.first().map(|(_, appdata)| appdata.clone()) else {
            continue;
        };
        let clashes = |appdata: &str, used: &HashSet<(String, String)>| {
            pairs
                .iter()
                .any(|(id, _)| used.contains(&(id.clone(), appdata.to_owned())))
        };
        let mut unique = appdata.clone();
        let mut n = 1u32;
        while clashes(&unique, &used) {
            let suffix = format!("-{n}");
            let keep = appdata.len().min(64 - suffix.len());
            unique = format!("{}{suffix}", &appdata[..keep]);
            n += 1;
        }
        for (id, _) in &pairs {
            used.insert((id.clone(), unique.clone()));
        }
        if unique == appdata {
            continue;
        }
        for a in media.attributes.iter_mut() {
            if a.value.is_none()
                && let Some(id) = a
                    .key
                    .strip_prefix("msid:")
                    .and_then(|v| v.split_once(' '))
                    .map(|(id, _)| id.to_owned())
            {
                a.key = format!("msid:{id} {unique}");
                continue;
            }
            let Some(value) = a.value.as_mut() else {
                continue;
            };
            if a.key == "msid" {
                if let Some((id, _)) = value.split_once(' ') {
                    *value = format!("{id} {unique}");
                }
            } else if a.key == ATTR_KEY_SSRC
                && let Some((ssrc, source)) = value.split_once(' ')
                && let Some(msid) = source.strip_prefix("msid:")
                && let Some((id, _)) = msid.split_once(' ')
            {
                *value = format!("{ssrc} msid:{id} {unique}");
            }
        }
    }
}

/// Inserts `a=<key>[:<value>]` at the end of m-section `index` of an SDP text, keeping every
/// other byte, with the text's own line ending. Returns the text unchanged if it has no such
/// m-section.
pub(crate) fn insert_media_line(sdp: &str, index: usize, key: &str, value: Option<&str>) -> String {
    let eol = if sdp.contains("\r\n") { "\r\n" } else { "\n" };
    let mut starts = vec![];
    let mut offset = 0;
    for line in sdp.split_inclusive('\n') {
        if line.starts_with("m=") {
            starts.push(offset);
        }
        offset += line.len();
    }
    if index >= starts.len() {
        return sdp.to_owned();
    }
    let end = starts.get(index + 1).copied().unwrap_or(sdp.len());
    let mut out = String::with_capacity(sdp.len() + key.len() + 64);
    out.push_str(&sdp[..end]);
    if !out.ends_with('\n') {
        out.push_str(eol);
    }
    out.push_str("a=");
    out.push_str(key);
    if let Some(value) = value {
        out.push(':');
        out.push_str(value);
    }
    out.push_str(eol);
    out.push_str(&sdp[end..]);
    out
}

